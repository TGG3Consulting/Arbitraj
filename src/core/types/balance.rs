//! Файл: core/types/balance.rs
//! Что делает: изменение баланса площадки или кошелька, которое адаптер увидел по событию (решение 76): поступление
//! перевода, свой вывод или обмен, постороннее изменение. По нему ядро закрывает ожидаемое зачисление перевода без
//! опроса статуса (core/credit_watch.rs), а неизвестные изменения пишет в журнал «внешнее изменение баланса».
//! Кто вызывает: адаптеры (событие MarketEvent::Balance), ядро (core/credit_watch.rs).
//! От чего зависит: core/types/market.rs.
//! Настройки: нет.
//!
//! Это стык: менять только через запрос на изменение стыка (docs/AGENTS.md).

use chrono::{DateTime, Utc};
use rust_decimal::Decimal;
use serde::{Deserialize, Serialize};

use super::market::{Asset, VenueId};

/// Что это за изменение — как его называет площадка.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum BalanceKind {
    /// Поступление перевода извне (депозит биржи; перевод токена или BNB на кошелёк не своей транзакцией).
    Deposit,
    /// Вывод с площадки (биржа сообщила вывод; чей он — решает ядро по своим переводам).
    Withdraw,
    /// Любое другое изменение (обмен, ордер, начисление площадки, перевод с кошелька не своей транзакцией).
    Other,
}

/// Одно изменение баланса одного актива.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BalanceChange {
    pub venue: VenueId,
    /// Актив: тикер так, как его знает ядро; адрес контракта — если площадка его знает (у кошелька — всегда).
    pub asset: Asset,
    /// Изменение: больше нуля — поступление, меньше — списание.
    pub delta: Decimal,
    pub kind: BalanceKind,
    /// Изменение сделал сам бот — адаптер знает это наверняка (у кошелька: транзакция от адреса кошелька;
    /// у биржи: ордер). Свои изменения — не зачисление перевода и не «внешнее изменение».
    pub own: bool,
    /// Хеш транзакции в сети, если площадка его сообщила.
    pub tx_hash: Option<String>,
    /// Момент, когда изменение стало окончательным по правилам площадки (кошелёк: нужное число подтверждений блока;
    /// биржа: время события). От него считается время в пути перевода (core/transit.rs).
    pub at: DateTime<Utc>,
    /// Откуда известно — для журнала (например «Transfer в блоке N» или «ACCOUNT_UPDATE m=DEPOSIT»).
    pub source: String,
}
