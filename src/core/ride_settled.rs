//! Файл: core/ride_settled.rs
//! Что делает: решение 464 (t238, живой NUM 20.11: Gate → DEX и три KuCoin → DEX продают в один пул PCS V3) — граница
//! «наша продажа уже в пуле / ещё нет» для расчёта продажи новой сделки при идущих сделках монеты (ride_quote.rs).
//! Правило Тиграна 20.11: новая сделка считает пул в текущем состоянии ПЛЮС сдвиг от всех своих идущих сделок, которые
//! ещё будут продавать в этот пул; продажа, уже исполненная в блоке, на котором посчитана котировка, — уже в состоянии
//! пула, её не добавляем; не исполненная (монета в пути, транзакция не в блоке) — добавляем её остаток.
//! Как это обеспечено (факт кода):
//! - остаток идущей сделки (Deal.qty, ride_quote::sell_ahead) уменьшается на проданное в момент итога ордера
//!   (credit_lock::selling), там же ставится след продажи с её блоком (ride_trail::note_fill); котировка по блоку НИЖЕ
//!   блока записанной продажи — отказ «не доказуемо свежее» (ride_trail::check): иначе пропуск проданных монет;
//! - между отправкой ордера продажи и его итогом учёт ещё не уменьшен, а транзакция могла уже лечь в блок, по которому
//!   взята котировка (двойной учёт) — или нет: по данным ядра не различить. Поэтому пока ордер продажи этой монеты на
//!   этой площадке в полёте (sale_marks::busy — только ордер; котировки-решения режима застрявшей монеты, перегона и
//!   «продать здесь» без ордера не держат) — котировки нет (отказ с причиной, следующий тик повторит);
//! - продажа, начатая и законченная, пока шла наша котировка, видна по счётчику итогов (sale_marks::sales) — отказ;
//! - исход нашей продажи монеты на площадке неизвестен (Deal.sale_unsure) — монета там заблокирована для новых сделок
//!   (unsure — и без идущих сделок, costs_source.rs; текст и уведомление — sale_marks.rs).
//!
//! Сделки других монет через общие промежуточные пулы и циклы DEX ↔ DEX здесь не учитываются (docs/TASKS.md, 464).
//! Кто вызывает: core/ride_quote.rs (live — продажа на B), core/costs_source.rs (unsure).
//! От чего зависит: sale_marks.rs (busy, sales, unsure_of), coin_ride.rs (идущие), engine.rs, core/types.
//! Настройки: нет (базовое поведение).

use crate::core::types::Direction;

use super::coin_key::CoinKey;
use super::engine::Core;
use super::sale_marks::MARK;

/// Что делает: проверка до котировки продажи — ордера нашей продажи этой монеты на площадке продажи в полёте нет.
/// Принимает: ядро, направление. Возвращает: счётчик итогов продаж (сравнить после котировки — after). Ошибки: текст
/// причины (ордер в полёте или исход неизвестен).
pub fn before(core: &Core, d: &Direction) -> Result<u64, String> {
    let seq = super::sale_marks::sales(core, &d.sell_on, &d.asset);
    in_flight(core, d)?;
    Ok(seq)
}

/// Что делает: проверка после котировки — за время котировки ни один наш ордер продажи монеты на площадке не начался
/// (в полёте) и не кончился (счётчик итогов тот же). Принимает: ядро, направление, счётчик из before. Ошибки: текст.
pub fn after(core: &Core, d: &Direction, seq: u64) -> Result<(), String> {
    in_flight(core, d)?;
    if super::sale_marks::sales(core, &d.sell_on, &d.asset) != seq {
        return Err(format!(
            "{}: наша продажа {} исполнилась, пока шла котировка — в каком блоке пула она уже есть, не сверено; \
             котировка повторится по пулу после неё {MARK}",
            d.sell_on.0, d.asset.ticker
        ));
    }
    Ok(())
}

/// Что делает: исход нашей продажи монеты на площадке продажи направления неизвестен — текст блокировки (для любого
/// расчёта продажи, и без идущих сделок). Принимает: ядро, направление. Возвращает: текст; None — блокировки нет.
/// Ошибок нет.
pub fn unsure(core: &Core, d: &Direction) -> Option<String> {
    let id = super::sale_marks::unsure_of(core, &d.sell_on, &d.asset)?;
    let deals = super::engine::lk(&core.inner.deals);
    Some(match deals.get(&id) {
        Some(x) => {
            let t = super::sale_marks::blocked_text(x);
            format!("{t} {MARK}")
        }
        None => format!(
            "монета {} на площадке {} заблокирована: исход продажи сделки {id} не известен — разберите сделку {MARK}",
            d.asset.ticker, d.sell_on.0
        ),
    })
}

/// Ордер продажи монеты на площадке продажи в полёте или исход нашей продажи там неизвестен. Ошибки: текст.
fn in_flight(core: &Core, d: &Direction) -> Result<(), String> {
    if super::sale_marks::busy(core, &d.sell_on, &d.asset) {
        return Err(format!(
            "{}: идёт наша продажа {} ({}) — попала ли она уже в пул, по которому считаем, не видно: ждём её итога, \
             чтобы не посчитать её монеты дважды или не пропустить {MARK}",
            d.sell_on.0,
            d.asset.ticker,
            riders(core, d)
        ));
    }
    match unsure(core, d) {
        Some(why) => Err(why),
        None => Ok(()),
    }
}

/// ID идущих сделок монеты, которые продают на площадке продажи направления (для текста). Ошибок нет.
fn riders(core: &Core, d: &Direction) -> String {
    let ids: Vec<String> = super::coin_ride::of_coin(core, &CoinKey::of(&d.asset))
        .into_iter()
        .filter(|r| r.sell_on == d.sell_on)
        .map(|r| r.deal_id)
        .collect();
    if ids.is_empty() {
        "сделка монеты".into()
    } else {
        format!("сделки {}", ids.join(", "))
    }
}
