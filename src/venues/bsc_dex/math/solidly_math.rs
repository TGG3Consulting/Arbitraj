//! Что делает: базовая математика инварианта СТАБИЛЬНОГО пула Solidly (решение 80 — экзотическая математика ve(3,3)-
//! форков) — порт официального контракта на целых числах U256, с теми же округлениями и той же итерацией
//! Ньютона — Рафсона, что в Solidity-исходнике. Инвариант стабильного пула: `x³y + xy³ = k` (нормализация к 1e18 по
//! decimals каждого токена). Три функции: `f` (значение кривой `x³y+xy³` при текущих x0,y), `d` (производная кривой по
//! y — для шага Ньютона) и `get_y` (новый нормализованный баланс встречного токена при заданном x0, цель `xy`).
//! Это чистая математика без сети; уровень свопа с комиссией и нормализацией по decimals (`get_amount_out`) — в
//! math/swap_solidly.rs. ТОЛЬКО стабильный инвариант: волатильные пулы тех же форков — обычный `x*y=k` (V2), уже
//! покрыт math/v2.rs, здесь не трогается.
//! Охват фазы A: только математика стабильного пула. Подключение семейств (Topaz v2-stable, THENA V1 stable),
//! чтение состояния пула, события, квотер и исполнение — следующая фаза.
//! Кто вызывает: math/swap_solidly.rs (get_amount_out); тесты (tests/bsc_dex_solidly_math.rs) — через переэкспорт.
//! От чего зависит: alloy-primitives (U256). Настройки: нет (резервы, decimals, комиссия — с контракта пула, фаза B).
//!
//! Источник (официальный, решение 23): velodrome-finance/contracts (HEAD b3065d8b6702b14b094f9f6046b752cc9f78c43b),
//! contracts/Pool.sol (pragma >=0.8.19): приватные `_f`, `_d`, `_get_y`. Solidity 0.8 проверяет всю арифметику
//! (+,-,* откатываются при переполнении/недоборе) → порт целиком на checked_*; где контракт откатился бы
//! (переполнение, вычитание ниже нуля, деление на ноль, `revert("!y")` при несходимости за 255 раундов) — `None`.
//! НЕ rust_decimal: целочисленно, ровно как uint256 контракта.

use alloy_primitives::U256;

/// Единица нормализации фикс-точки на 18 знаков (контракт: литерал 1e18). Ошибок нет.
pub fn e18() -> U256 {
    U256::from(10u8).pow(U256::from(18u8))
}

/// Знаменатель комиссии пула (контракт: деление комиссии на 10000; getFee — доля над 10000). Ошибок нет.
pub fn fee_denominator() -> U256 {
    U256::from(10_000u16)
}

/// Pool._f: значение кривой `x³y + xy³` в масштабе 1e18 при текущих x0,y (оба нормализованы к 1e18).
/// Контракт: `_a = x0·y/1e18; _b = x0²/1e18 + y²/1e18; return _a·_b/1e18`. Принимает: x0, y. Возвращает: f.
/// None — переполнение любого из умножений (в контракте checked `*` откатился бы).
pub fn f(x0: U256, y: U256) -> Option<U256> {
    let one = e18();
    let a = x0.checked_mul(y)? / one;
    let b = (x0.checked_mul(x0)? / one).checked_add(y.checked_mul(y)? / one)?;
    Some(a.checked_mul(b)? / one)
}

/// Pool._d: производная кривой по y (для шага Ньютона), в масштабе 1e18. Оба аргумента нормализованы к 1e18.
/// Контракт: `3·x0·(y²/1e18)/1e18 + (((x0²/1e18)·x0)/1e18)`. Принимает: x0, y. Возвращает: d.
/// None — переполнение любой операции (в контракте checked откатился бы).
pub fn d(x0: U256, y: U256) -> Option<U256> {
    let one = e18();
    let three = U256::from(3u8);
    // Порядок как в контракте: ((3·x0)·(y²/1e18))/1e18.
    let term1 = three
        .checked_mul(x0)?
        .checked_mul(y.checked_mul(y)? / one)?
        / one;
    // (((x0²/1e18)·x0)/1e18).
    let term2 = (x0.checked_mul(x0)? / one).checked_mul(x0)? / one;
    term1.checked_add(term2)
}

/// Pool._get_y: методом Ньютона — Рафсона найти новый нормализованный баланс встречного токена y, при котором кривая
/// `_f(x0, y)` достигает цели `xy`, когда баланс исходного токена стал равен x0 (все значения нормализованы к 1e18).
/// Ровно как в контракте: до 255 раундов, шаг `dy = |xy − f(x0,y)|·1e18 / _d(x0,y)`, с обработкой `dy == 0`
/// (сходимость либо коррекция ±1). Принимает: x0 — новый нормализованный баланс исходного токена; xy — цель
/// (инвариант до свопа); y — стартовое приближение (текущий нормализованный баланс встречного токена).
/// Возвращает: новый нормализованный баланс встречного токена. None — переполнение/недобор, деление на ноль
/// (`_d` = 0) или несходимость за 255 раундов (контракт: `revert("!y")`).
pub fn get_y(x0: U256, xy: U256, mut y: U256) -> Option<U256> {
    let one = e18();
    for _ in 0..255u16 {
        let k = f(x0, y)?;
        if k < xy {
            let dd = d(x0, y)?;
            if dd.is_zero() {
                return None; // контракт: деление на ноль откатилось бы
            }
            let mut dy = (xy - k).checked_mul(one)? / dd;
            if dy.is_zero() {
                if k == xy {
                    return Some(y);
                }
                if f(x0, y.checked_add(U256::from(1u8))?)? > xy {
                    return Some(y + U256::from(1u8));
                }
                dy = U256::from(1u8);
            }
            y = y.checked_add(dy)?;
        } else {
            let dd = d(x0, y)?;
            if dd.is_zero() {
                return None;
            }
            let mut dy = (k - xy).checked_mul(one)? / dd;
            if dy.is_zero() {
                // k == xy — сошлись; либо f(x0, y−1) < xy — ближе не подойти (нужно f ≥ xy, y−1 нельзя).
                if k == xy || f(x0, y.checked_sub(U256::from(1u8))?)? < xy {
                    return Some(y);
                }
                dy = U256::from(1u8);
            }
            y = y.checked_sub(dy)?;
        }
    }
    None // контракт: revert("!y") — не сошлось за 255 раундов
}
