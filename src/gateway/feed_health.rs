//! Файл: gateway/feed_health.rs
//! Что делает: решение 202 (Тигран, 06.11.2026: «переподписка не биржи, а именно пачки») — типы стыка «сторож пар»:
//! снимок свежести потока стаканов адаптера по соединениям (пачкам пар) и команды «переподписать пару» /
//! «переподключить соединение». Ядро (core/feed_watch.rs) решает по сделкам и счётчикам; адаптер только отдаёт
//! свежесть и выполняет команду. Общий для адаптеров учёт свежести — gateway/feed_reg.rs.
//! Кто вызывает: gateway/contract.rs (методы feed_health, resubscribe_pair, reconnect_conn), gateway/feed_reg.rs,
//! core/feed_watch.rs.
//! От чего зависит: ничего.
//! Настройки: нет (пороги сторожа — core/feed_watch.rs).

/// Свежесть одной пары соединения (unix мс).
#[derive(Debug, Clone, PartialEq)]
pub struct PairHealth {
    pub ticker: String,
    /// Последний кадр стакана пары; None — с начала соединения кадров не было.
    pub last_ms: Option<i64>,
    /// Когда пара (пере)подписана — с этого момента идёт прогрев.
    pub since_ms: i64,
}

/// Свежесть одного соединения (пачки пар).
#[derive(Debug, Clone, PartialEq)]
pub struct ConnHealth {
    /// Имя соединения адаптера («market-3»).
    pub conn: String,
    /// Последний кадр соединения любого вида (стакан, понг, ответ); None — сессии ещё нет.
    pub alive_ms: Option<i64>,
    /// Начало текущей сессии соединения (подключение) — прогрев.
    pub started_ms: Option<i64>,
    pub pairs: Vec<PairHealth>,
}

/// Снимок свежести потока стаканов площадки.
#[derive(Debug, Clone, PartialEq)]
pub struct FeedHealth {
    /// Кадры стакана приходят по расписанию даже без изменений (по документации площадки): только тогда тишина пары
    /// = мёртвая пара. Нет — сторож для площадки выключен.
    pub scheduled: bool,
    /// Можно переподписать одну пару без обрыва соединения (отписка + подписка в документации канала).
    pub per_pair: bool,
    pub conns: Vec<ConnHealth>,
}

/// Команда соединению.
#[derive(Debug, Clone, PartialEq)]
pub enum Cmd {
    /// Переподписать одну пару (тикер ядра).
    Resub(String),
    /// Переподключить соединение с теми же парами.
    Reconnect,
}
