//! Файл: core/deposit_proof_plan.rs
//! Что делает: решение 411 (задача t196, переделка «по триггеру») — чистая логика адреса депозита биржи-получателя:
//! брать ли адрес из памяти без запроса; сверка ответа триггерного запроса с прежней памятью — совпал, изменился или в
//! памяти не было; тексты журнала и Telegram — без значений адреса и memo.
//! Повторное ревью: снимать ли пометку «спросить заново» ответом запроса (clears); повтор запроса адреса в выводе по
//! правилу шлюза — без побочных действий операции вывода (addr_retry).
//! Кто вызывает: core/deposit_proof.rs, core/transfers.rs (addr_retry), tests/core_deposit_proof_411.rs.
//! От чего зависит: gateway/rules.rs, gateway/errors.rs (типы).
//! Настройки: нет.

use crate::gateway::errors::ErrorCode;
use crate::gateway::rules::{self, RuleAction};

/// Итог сверки ответа биржи с памятью.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Seen {
    /// Совпал с адресом в памяти.
    Same,
    /// Другой адрес: память обновлена (адаптер положил ответ), событие в журнал и Telegram.
    Changed,
    /// В памяти адреса не было — сверять не с чем.
    First,
}

/// Что делает: сверка ответа биржи с памятью. Принимает: адрес из памяти (None — не было), адрес из ответа.
/// Возвращает: Seen. Ошибок нет.
pub fn compare(memory: Option<&str>, fresh: &str) -> Seen {
    match memory {
        None => Seen::First,
        Some(m) if m == fresh => Seen::Same,
        Some(_) => Seen::Changed,
    }
}

/// Что делает: брать ли адрес из памяти без запроса к бирже. Принимает: есть ли адрес в памяти (под текущим ключом
/// API), стоит ли пометка «спросить заново» (триггеры в, г). Возвращает: true — из памяти; false — запрос (триггер).
/// Ошибок нет.
pub fn use_memory(in_memory: bool, doubted: bool) -> bool {
    in_memory && !doubted
}

/// Что делает: текст журнала и Telegram «адрес изменился» — без значений адреса и memo. Принимает: площадку, монету,
/// сеть. Возвращает: текст. Ошибок нет.
pub fn changed_text(venue: &str, ticker: &str, net: &str) -> String {
    format!(
        "{venue}: адрес депозита {ticker} в сети {net} изменился — ответ биржи на повторный запрос адреса не совпал с \
         адресом в памяти бота. Сделано: память обновлена на адрес из ответа биржи; дальше предпроверка и вывод на \
         {venue} берут новый адрес"
    )
}

/// Что делает: текст журнала «адрес будет запрошен заново» — без значений адреса. Принимает: площадку, монету, сеть,
/// причину (триггер). Возвращает: текст. Ошибок нет.
pub fn doubt_text(venue: &str, ticker: &str, net: &str, why: &str) -> String {
    format!(
        "{venue}: адрес депозита {ticker} в сети {net} будет запрошен у биржи заново при следующей предпроверке или \
         выводе — {why}"
    )
}

/// Что делает: снимает ли удачный ответ пометку «спросить заново». Принимает: номер пометки, последний номер пометок
/// на начало запроса. Возвращает: true — пометка поставлена до начала запроса (ответ её покрывает); false — пометку
/// поставили, пока запрос шёл (снимет следующий запрос). Ошибок нет.
pub fn clears(mark: u64, started: u64) -> bool {
    mark <= started
}

/// Что делает: повтор запроса адреса депозита в выводе по правилу шлюза для кода ошибки — только «повторить N раз с
/// паузой» (RuleAction::Retry), без побочных действий операции вывода (уведомлений, ошибок подряд, пауз площадки):
/// это ещё не вывод. Исход неизвестен и отказы вывода (rules::retry_allowed, withdraw_refusal) не повторяются.
/// Принимает: действие выбранного правила (None — правила нет), код ошибки, номер попытки (с 1).
/// Возвращает: пауза перед повтором, мс; None — не повторять. Ошибок нет.
pub fn addr_retry(rule: Option<&RuleAction>, code: ErrorCode, attempt: u32) -> Option<u64> {
    if !rules::retry_allowed(code) || rules::withdraw_refusal(code) {
        return None;
    }
    match rule {
        Some(RuleAction::Retry { attempts, pause_ms }) if attempt <= *attempts => Some(*pause_ms),
        _ => None,
    }
}
