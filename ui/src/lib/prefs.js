// Файл: ui/src/lib/prefs.js
// Что делает: удобства одного зрителя в браузере (например, сколько записей журнала показывать за раз).
//   Только то, что не секрет и не влияет на систему. Значения секретов сюда не пишутся никогда.
//   Хранилище браузера может быть недоступно (приватное окно) — тогда просто ничего не запоминается.
// Кто вызывает: components/PageSize.svelte.
// От чего зависит: localStorage браузера.
// Настройки: нет.

/** Читает значение. Принимает: ключ. Возвращает: строку или '' (нет или хранилище недоступно). */
export function load(key) {
  try {
    return localStorage.getItem(`arb.${key}`) ?? '';
  } catch {
    return '';
  }
}

/** Запоминает значение. Принимает: ключ, строку. Ошибки: молча не запоминает, если хранилище недоступно. */
export function save(key, value) {
  try {
    localStorage.setItem(`arb.${key}`, value);
  } catch {
    // Хранилище недоступно — экран работает, просто не запомнит выбор.
  }
}
