//! Файл: venues/htx/book_rule.rs
//! Что делает: решение 422 — состояние одной пары HTX в выборе «быстрый стакан / снимок» (book_mode.rs) и правила без
//! замков и сети: «не старее отданного» по времени биржи, уход на запасной снимок, сверка снимка mbp.refresh с быстрым
//! стаканом. Вынесено из book_mode.rs (ориентир 200 строк; решение 422, ревью).
//! Кто вызывает: book_mode.rs (под замком пар), тесты через book_mode.rs.
//! От чего зависит: book.rs (Alive), book_mode.rs (Back), core/types.
//! Настройки: нет.
//!
//! Сверка по содержимому (решение 422, ревью; то же правило, что в ревью 420, 421, 424): номера двух каналов не
//! сравнимы (связь seqNum mbp.refresh и mbp.$levels документация не описывает), но ts кадров — мс HTX у обоих. Снимок
//! с ts строго больше ts последнего отданного быстрого стакана показывает книгу после него; два таких снимка ПОДРЯД не
//! совпали с верхом быстрого, а быстрый между ними не менялся (та же версия) — быстрый молчит о реальном изменении
//! дольше периода снимков (~100 мс, «The update interval is around 100ms»): расхождение при целой цепочке номеров.
//! Прежнее правило автора («не подтверждён дольше venue.book_stale_ms») у активной пары не срабатывало никогда: каждый
//! кадр быстрого потока (у 150 уровней — и пустой раз в 100 мс) подтверждал стакан.

use crate::core::types::OrderBook;

use super::book::Alive;
use super::book_mode::Back;

/// Пара.
#[derive(Default)]
pub(super) struct Pair {
    /// Ядру отдаётся быстрый стакан.
    pub fast: bool,
    /// Время биржи (мс) последнего отданного ядру стакана.
    pub last_ms: Option<i64>,
    /// Последний снимок mbp.refresh и живость его соединения.
    pub spare: Option<(OrderBook, Alive)>,
    /// Версия быстрого стакана: +1 на каждую отдачу быстрого ядру.
    pub ver: u64,
    /// Версия быстрого при прошлом несовпавшем снимке новее него (сверка).
    pub miss: Option<u64>,
    /// Расхождение объявлено, а быстрый ещё не пересинхронизирован: на быстрый нельзя до нового снимка req (иначе
    /// следующее изменение старого локального стакана вернуло бы пару на неверный быстрый до сброса).
    pub blocked: bool,
}

/// Время биржи стакана (мс). Ошибок нет.
pub fn ts(b: &OrderBook) -> Option<i64> {
    b.exchange_time.map(|t| t.timestamp_millis())
}

/// Старее ли ts уже отданного (нет одного из времён — нет). Ошибок нет.
pub fn older(ts: Option<i64>, last: Option<i64>) -> bool {
    matches!((ts, last), (Some(t), Some(l)) if t < l)
}

/// Уход пары с быстрого стакана (пара должна быть на быстром): запасной снимок, если он не старее отданного, иначе
/// «недостоверен». Ошибок нет.
pub(super) fn leave(p: &mut Pair) -> Back {
    p.fast = false;
    p.miss = None;
    match &p.spare {
        Some((b, a)) if !older(ts(b), p.last_ms) => {
            p.last_ms = ts(b).or(p.last_ms);
            Back::Use(b.clone(), a.clone())
        }
        _ => Back::Invalidate,
    }
}

/// Сверка нового снимка (запасной уже обновлён) с быстрым стаканом пары на быстром. Принимает: пару, совпал ли верх.
/// Возвращает: true — второй подряд снимок новее быстрого и не равен ему, а быстрый между ними не менялся. Ошибок нет:
/// нет ts у снимка или у быстрого — сравнить по времени нельзя, расхождение не объявляется.
pub(super) fn diverged(p: &mut Pair, same: bool) -> bool {
    let snap = p.spare.as_ref().and_then(|(s, _)| ts(s));
    let newer = matches!((snap, p.last_ms), (Some(s), Some(f)) if s > f);
    if same || !newer {
        p.miss = None;
        return false;
    }
    if p.miss == Some(p.ver) {
        p.miss = None;
        return true;
    }
    p.miss = Some(p.ver);
    false
}
