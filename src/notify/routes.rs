//! Файл: notify/routes.rs
//! Что делает: маршрутизация исходящих событий по ролям чатов (решение 176) — таблица в одном месте.
//! «Общий» (General) получает все события по-прежнему — по настройкам событий notify.event.* (dispatch.rs), кроме
//! таблицы NOT_GENERAL (решение 251 (г), ниже). Сверх этого событие уходит в чаты ролей из таблицы ROUTES — если роль задана (notify/roles.rs::chat);
//! фильтры notify.event.* к чатам ролей не применяются: задать чат роли и значит включить её.
//! Зеркало «Ручного управления» (manual.record, решение 156) — не по этой таблице: у него своё сообщение с кнопками и
//! напоминания (notify/mirror*.rs), его чат — roles::mirror_role («Неудачные», если задан, иначе «Общий»); оно, как и
//! раньше, уходит по настройкам события manual.record (notify.event.enabled / venues).
//! Выбор по сделке: закрытая сделка — в «Сделки» с любым итогом (решение 191, Тигран 06.11.2026: «итог минусовой
//! сделки точно так же, как и плюсовой, отправляется именно в чат удачных сделок»; было — минусовая в «Неудачные»).
//! Остановленная или переданная человеку сделка в «Сделки» не идёт — её запись с кнопками уходит в «Неудачные»
//! зеркалом «Ручного управления».
//! Решение 230: пауза от сверки балансов (risk.reconcile_paused) — ещё и в «Неудачные».
//! Решение 251, ответ (г) Тиграна 10.11: событие из таблицы NOT_GENERAL в «Общий» не идёт, если задан чат его роли
//! (deal.closed — итог есть в «Сделки»; stuck.loss_alert — та же запись с кнопками в «Неудачные», manual.record); чат
//! роли не задан — «Общий», как раньше (чтобы не потерять).
//! Кто вызывает: notify/dispatch_role.rs (send_tagged), notify/dispatch.rs (deliver — not_general).
//! От чего зависит: notify/roles.rs, settings.
//! Настройки: нет своих (чаты ролей — notify/roles.rs: notify.deals_chat, notify.failures_chat).

use crate::settings::store::Store;

use super::roles::{self, Role};

/// Признак события для маршрута (у закрытия сделки — знак итога).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Tag {
    /// Без признака.
    Plain,
    /// Сделка закрыта с итогом ≥ 0 (core/deal_text.rs::outcome).
    Profit,
    /// Сделка закрыта с итогом < 0.
    Loss,
}

/// Таблица маршрутов: (код события из notify/catalog.rs, признак, роли сверх «Общего»).
#[rustfmt::skip]
pub static ROUTES: &[(&str, Tag, &[Role])] = &[
    ("deal.closed", Tag::Profit, &[Role::Deals]),
    // Решение 191 (Тигран, 06.11.2026): итог минусовой сделки — как и плюсовой, в чат «Сделки», не в «Неудачные».
    ("deal.closed", Tag::Loss, &[Role::Deals]),
    // Решение 230 (Тигран, 08.11.2026): сверка поставила паузу площадке или кошельку DEX — короткое сообщение в чат
    // проблем «Неудачные».
    ("risk.reconcile_paused", Tag::Plain, &[Role::Failures]),
];

/// Решение 251 (г): (код события, роль) — событие НЕ идёт в «Общий», если чат роли задан (roles::chat).
#[rustfmt::skip]
pub static NOT_GENERAL: &[(&str, Role)] = &[
    // Итог сделки — в «Сделки» (ROUTES); в «Общем» был дублем.
    ("deal.closed", Role::Deals),
    // Алерт без кнопок; та же запись с кнопками — в «Неудачные» дублем «Ручного управления» (manual.record).
    ("stuck.loss_alert", Role::Failures),
];

/// Не слать ли событие в «Общий»: оно в NOT_GENERAL и чат его роли задан. Принимает: настройки, код.
/// Возвращает: роль, куда событие идёт вместо «Общего», или None — в «Общий», как раньше. Ошибок нет.
pub fn not_general(settings: &Store, code: &str) -> Option<Role> {
    NOT_GENERAL
        .iter()
        .find(|(c, r)| *c == code && roles::chat(settings, *r).is_some())
        .map(|(_, r)| *r)
}

/// Роли сверх «Общего» для события. Принимает: код, признак. Возвращает: роли (пусто — только «Общий»). Ошибок нет.
pub fn extra(code: &str, tag: Tag) -> &'static [Role] {
    ROUTES
        .iter()
        .find(|(c, t, _)| *c == code && *t == tag)
        .map(|(_, _, r)| *r)
        .unwrap_or(&[])
}
