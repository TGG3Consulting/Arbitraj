// исключение each_key_duplicate (живая консоль 07.11.2026: экран падал на отрисовке). uniq — повторяющиеся строки
// (имена площадок, адреса, тикеры, ссылки, варианты выбора) показываются один раз; uniqBy — одна и та же сущность из
// двух источников (страница + живое сообщение, «Ещё») — остаётся первая (новее — та, что раньше в списке).
// Кто вызывает: pages/*, components/* с keyed-блоками по данным API.
// От чего зависит: ничего.
// Настройки: нет.

/** Строки (или числа) без повторов, порядок первого появления. Принимает: список или null. Ошибок нет. */
export const uniq = (list) => [...new Set(list ?? [])];

/**
 * Элементы без повторов ключа, порядок первого появления (первый побеждает).
 * Принимает: список (или null), функцию ключа. Возвращает: новый массив. Ошибок нет.
 */
export function uniqBy(list, key) {
  const seen = new Set();
  const out = [];
  for (const x of list ?? []) {
    const k = key(x);
    if (seen.has(k)) continue;
    seen.add(k);
    out.push(x);
  }
  return out;
}
