//! Файл: venues/bsc_dex/node/priority.rs
//! Что делает: класс срочности запросов к узлу BSC по HTTP (решение 61). Очередь узла (node/pace.rs) отдаёт
//! освободившееся место сначала сделке, потом проверкам монет, потом фоновой работе — строгий порядок: запрос
//! младшего класса уходит, только когда старших в очереди нет. Внутри класса — по порядку прихода.
//!   Trade — путь сделки: расчёт перед сделкой (квотер «сейчас», проба перед отправкой), подпись, отправка,
//!           слежение за транзакцией, вывод и сверки по сделке.
//!   Check — проверки монет и крючков (пробный обмен налогов, пробы крючков, перепроверка).
//!   Background — всё остальное: загрузка и проверка пулов, цикл квотера, балансы, газ.
//! Класс задаётся на задачу tokio (task_local): у вызывающего — `scope(класс, работа)`; не задан — Background.
//! Порядок классов — свойство конвейера (сделка не ждёт проверок, проверки не ждут фона), не настройка:
//! числа в нём нет, темп по-прежнему один — bsc.node_http_rps.
//! Кто вызывает: node/pace.rs (current), mod.rs (Trade), pools/market.rs и check/* (Check), exec/txs.rs (Trade).
//! От чего зависит: tokio (task_local).
//! Настройки: нет.

use std::future::Future;

/// Класс срочности. Порядок объявления — порядок очереди (меньше — раньше).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Class {
    /// Путь сделки.
    Trade,
    /// Проверки монет и крючков.
    Check,
    /// Фон: пулы, квотер-цикл, прочее.
    Background,
}

tokio::task_local! {
    static CLASS: Class;
}

/// Класс текущей задачи. Не задан — Background. Ошибок нет.
pub fn current() -> Class {
    CLASS.try_with(|c| *c).unwrap_or(Class::Background)
}

/// Выполняет работу с классом `class` (все запросы к узлу внутри неё, кроме запущенных отдельными задачами tokio —
/// им класс задают при запуске). Принимает: класс, работу. Возвращает: её результат. Ошибок нет.
pub async fn scope<F: Future>(class: Class, work: F) -> F::Output {
    CLASS.scope(class, work).await
}
