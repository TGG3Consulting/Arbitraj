//! Что делает: решение 236, дополнение п. 2 (техлид 09.11 по поручению Тиграна) — «Перегнано вручную» спрашивает, сколько
//! USDT зачислено на площадке покупки (ответ человека числом, как в «Продано вручную»): кнопка с вводом и разбор
//! ответа. Затраты возврата части = сумма части − зачислено (deal_return_cost.rs part_cost); «-» — человек не знает.
//! Кто вызывает: core/manual_usdt.rs (запись «USDT не вернулись», команда UsdtReturnedManually).
//! От чего зависит: manual_rows.rs (btn), core/types (ManualAction, ManualButton).
//! Настройки: нет.

use rust_decimal::Decimal;

use crate::core::types::{ManualAction as A, ManualButton};

use super::manual_rows::btn;

/// Кнопка «Перегнано вручную» с вводом (решение 236, дополнение п. 2, техлид 09.11): бот спрашивает, сколько USDT
/// зачислено на площадке покупки — ответ человека числом, как в «Продано вручную»; затраты возврата части = сумма части
/// − зачислено — в итог сделки. «-» — человек не знает: затраты в итог не входят, пометка. Принимает: ключ части, id
/// сделки, (где лежат, куда), сумму части (округлённую для текста). Ошибок нет.
pub fn button(key: &str, id: &str, (v, to): (&str, &str), sum: Decimal) -> ManualButton {
    let mut b = btn(
        "usdt_manual",
        "Перегнано вручную",
        A::UsdtReturnedManually {
            deal_id: key.to_string(),
            usdt: None,
        },
        format!(
            "Отметить, что {sum} USDT сделки {id} вы перевели с {v} на {to} сами? Зачислено: {{usdt}} USDT («-» — не знаете). Запись закроется, бот этот возврат больше не делает; затраты возврата (сумма части − зачислено) войдут в итог сделки."
        ),
        None,
        true,
    );
    b.input = Some(format!(
        "Сколько USDT зачислено на {to}? Сумма части {sum} USDT с {v}; затраты возврата = {sum} − зачислено войдут в итог сделки. Не знаете — введите «-»: затраты в итог не войдут."
    ));
    b
}

/// Ответ «сколько зачислено» (решение 236, дополнение п. 2). Принимает: ввод (None или «-» — не знает), сумму части.
/// Возвращает: Ok(None) — не знает; Ok(Some(зачислено)). Ошибки: не число, меньше нуля, больше суммы части (затраты
/// стали бы отрицательными — итог вырос бы без факта) — причина и просьба проверить.
pub fn parse(usdt: Option<&str>, amount: Decimal) -> Result<Option<Decimal>, String> {
    let Some(u) = usdt.map(str::trim).filter(|u| !u.is_empty() && *u != "-") else {
        return Ok(None);
    };
    let c: Decimal = u
        .replace(',', ".")
        .parse()
        .map_err(|_| format!("«{u}» — не число USDT; введите сумму зачисления или «-»"))?;
    if c < Decimal::ZERO {
        return Err(format!("зачислено {c} USDT — меньше нуля; проверьте сумму"));
    }
    if c > amount {
        return Err(format!(
            "зачислено {c} USDT больше суммы части {amount} USDT — так быть не может (затраты возврата стали бы отрицательными); проверьте сумму"
        ));
    }
    Ok(Some(c))
}
