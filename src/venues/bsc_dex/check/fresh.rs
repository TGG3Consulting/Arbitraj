//! Файл: venues/bsc_dex/check/fresh.rs
//! Что делает: какие пулы цикла проверок (сверка с квотером, крючки) ещё ни разу не проверены этим циклом — их
//! проверяют сразу, как только пул стал достоверным (прочитан при старте, перечитан, принят новым), а не через
//! интервал полного прохода (решение 65: пулы, дочитанные после старта цикла, ждали dex.quoter_check_s — 15 минут
//! без цен). И когда первый проход окончен: ни один пул не читается (pools/loading.rs reading — застрявшие из-за
//! незаданной настройки не в счёт, как у налогов, решение 63) и все достоверные пулы проверены.
//! Решение 310 (задача t141): при dex.check_due_read_only = да достоверность пула в due() читается без записи
//! (pools/registry.rs entry — блокировка на чтение, без копии записи), а не через update: update существующего пула
//! всегда отмечает пул изменённым для фонового графа (graph_changes.rs) и растит версию реестра — один вызов due()
//! давал столько отметок и ростов версии, сколько пулов в реестре (живой бот 16.11.2026: 13 457), и фоновый владелец
//! графа пересчитывал почти весь реестр за круг. Не задана или нет — как раньше (через update).
//! С2 (ревью 28.11.2026): сводка — не раньше конца первого прохода справочника (directory/boot.rs).
//! Кто вызывает: check/quoter_cycle.rs, check/cycle.rs.
//! От чего зависит: pools/listen.rs (Pools: реестр, «загружаются», окружение — настройки), pools/registry.rs (entry,
//! update).
//! Настройки: dex.check_due_read_only (решение 310, необязательная; docs/SETTINGS.md).

use std::collections::HashSet;

use crate::core::types::PoolRef;

use super::super::pools::listen::Pools;

/// Пулы, уже проверенные циклом хотя бы раз (любой итог, в том числе «мельче порога» — проверять нечего).
#[derive(Default)]
pub struct Fresh {
    seen: HashSet<PoolRef>,
}

impl Fresh {
    /// Достоверные пулы реестра, которые надо проверить сейчас: ещё не проверенные циклом и те, для которых `again`
    /// (например, сверка ждала влияния крючка, а оно уже измерено). Принимает: окружение, условие повтора.
    /// Возвращает: пулы. Ошибок нет.
    /// Решение 310: способ чтения достоверности (dex.check_due_read_only) читается один раз на вызов.
    pub fn due(&self, p: &Pools, again: impl Fn(&PoolRef) -> bool) -> Vec<PoolRef> {
        let ro = read_only(p);
        p.reg
            .refs()
            .into_iter()
            .filter(|r| valid(p, r, ro))
            .filter(|r| !self.seen.contains(r) || again(r))
            .collect()
    }

    /// Проверка пула циклом: отмечается проверенным, только если проверка была (`run` вернул true). Пул, недостоверный
    /// во время полного прохода или «Перепроверить», не отмечается — проверится сразу, как только станет достоверным.
    /// Принимает: пул, проверку. Ошибок нет.
    pub async fn check(&mut self, r: &PoolRef, run: impl std::future::Future<Output = bool>) {
        if run.await {
            self.mark(r);
        }
    }

    /// Пул проверен циклом. Ошибок нет.
    pub fn mark(&mut self, r: &PoolRef) {
        self.seen.insert(r.clone());
    }

    /// Первый проход окончен: первый проход справочника подписки окончен (С2, directory/boot.rs: индексатор и поиск по
    /// фабрикам, их монеты обработаны — иначе сводка уходила при нуле пулов), ни один пул не читается и все достоверные
    /// пулы проверены. Ошибок нет.
    pub fn settled(&self, p: &Pools) -> bool {
        super::super::directory::boot::complete(&p.ctx)
            && !p.loading.reading(p)
            && self.due(p, |_| false).is_empty()
    }
}

/// Что делает: решение 310 — читать ли достоверность пула без записи (dex.check_due_read_only).
/// Принимает: окружение. Возвращает: true — «да»; не задана, «нет» или ошибка чтения настройки — false (как раньше).
/// Ошибок нет.
fn read_only(p: &Pools) -> bool {
    p.ctx.flag("dex.check_due_read_only").unwrap_or(false)
}

/// Что делает: достоверен ли пул реестра. `read_only` (решение 310) — чтение без записи: запись не копируется, пул не
/// отмечается изменённым для фонового графа, версия реестра не растёт. Иначе — как раньше, через update (отметка и
/// рост версии на каждый пул). Принимает: окружение, ссылку на пул, способ чтения.
/// Возвращает: true — пул есть и достоверен; пула нет — false. Ошибок нет.
fn valid(p: &Pools, r: &PoolRef, read_only: bool) -> bool {
    if read_only {
        p.reg.entry(r).is_some_and(|e| e.valid)
    } else {
        p.reg.update(r, |e| e.valid).unwrap_or(false)
    }
}
