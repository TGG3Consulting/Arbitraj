//! Файл: report/cap_notes.rs
//! Что делает: решение 256 (с дополнением — аудит отчёта, п. 1, 7, 8, 12) — примечания листа «Итоги» отчёта «Сделки,
//! лимиты и капитал»: точное окно выгрузки и время выгрузки, правила отбора и столбцов — по факту кода (конец сделки —
//! запись закрытия в хронологии, report/rows_time.rs ended_at; занятость — report/cap_hold.rs; адреса —
//! report/cap_addr.rs), ограничение хранения записей «без потолка» (значение uncapped.keep_days на момент выгрузки),
//! причины, по которым данных нет.
//! Кто вызывает: report/cap_send.rs (capital_data).
//! От чего зависит: report/rows_time.rs (Window).
//! Настройки: нет (значение uncapped.keep_days приходит готовым).

use super::rows_time::Window;

/// Что нужно примечаниям: окно, число несравнимых записей сделок, причины без данных, срок хранения «без потолка».
pub struct NotesIn<'a> {
    pub window: &'a Window,
    pub incomparable: u64,
    pub ladder_error: Option<&'a str>,
    pub off: Option<&'a str>,
    /// uncapped.keep_days на момент выгрузки (Err — почему не прочитано).
    pub keep_days: Result<u64, String>,
}

/// Примечания листа «Итоги» (см. шапку). Ошибок нет.
pub fn notes(x: &NotesIn) -> Vec<String> {
    let w = x.window;
    let mut v = vec![
        format!("Окно выгрузки (UTC): {}.", w.text()),
        format!("Выгрузка: {} UTC.", w.now.format("%Y-%m-%d %H:%M:%S")),
        "Дни — календарные UTC, как в «Итогах сделок»: «текущий день» — с 00:00 UTC сегодня, «N дней» — с 00:00 UTC \
         дня (сегодня − (N − 1)), до момента выгрузки; свой интервал — с 00:00 первой даты по 24:00 второй."
            .into(),
        "Лист «Сделки»: все сделки, которые касаются окна, — закончились в нём, открыты или начаты раньше, но деньги \
         покупки ещё заняты в окне. «В итоге периода» = отбор «Итогов сделок» (закончилась в окне и двигала деньги); \
         у остальных — «Почему не в итоге». Таблица 2 «Итог периода» = «Итог факт + оценка» «Итогов сделок» за то же окно."
            .into(),
        "Конец сделки — запись закрытия в хронологии сделки (переход в «закрыта» / «остановлена» / «монеты у человека»), \
         та же функция, что «Длительность» в «Итогах сделок»; возврат USDT после закрытия в конец не входит. У открытой \
         сделки конца нет; закрытая без записи конца — пометка «конец не найден», в расчёт занятости не входит."
            .into(),
        "«Покупка состоялась» — у сделки есть исполненная покупка; у «Вернуть боту» (<id>r) покупки нет, вложено — доля \
         исходной сделки, её занятость считается у исходной (вложено не учитывается дважды)."
            .into(),
        "Занятость денег покупки: площадка — биржа покупки, у покупки на DEX — кошелёк сделки; сумма — «Вложено»; с \
         начала сделки до возврата USDT на площадку покупки (время записи «USDT вернулись» / «Перегнано вручную»); \
         продано там же или возврата у сделки нет — до конца сделки; возврат идёт / не вернулись, остановлена с \
         монетами, открыта — занято до выгрузки. Пояснение — в столбце «Занятость — пояснение»."
            .into(),
        "Адреса: пулы — маршрут, отправленный в ордер DEX; у цикла DEX ↔ DEX — маршрут плана цикла (в ордер цикла \
         маршрут не пишется); кошелёк — адрес счёта DEX сделки; хеши и id — из учёта сделки. Хеши возврата USDT в учёте \
         сделки не хранятся — их в книге нет."
            .into(),
        "Эпизод «без потолка» = направление (монета + биржи) + начало эпизода; по эпизоду — наибольшая прибыль на \
         нашем бюджете и на каждом потолке модели (uncapped.ladder_usdt); «что ограничило» — у пиковой записи эпизода."
            .into(),
    ];
    v.push(match &x.keep_days {
        Ok(n) => format!(
            "Лист «Упущено из-за потолка»: записи «без потолка» хранятся uncapped.keep_days = {n} дн. (на момент \
             выгрузки) — более старых в книге нет, даже «за всё время»; лист «Сделки» — весь учёт."
        ),
        Err(e) => format!(
            "Лист «Упущено из-за потолка»: срок хранения записей uncapped.keep_days не прочитан ({e})."
        ),
    });
    if x.incomparable > 0 {
        v.push(format!(
            "Записи сделок «без потолка» не по данным момента входа (решение 239) не входят: {}.",
            x.incomparable
        ));
    }
    if let Some(e) = x.ladder_error {
        v.push(format!(
            "Потолки модели не заданы: {e} — столбцов потолков нет."
        ));
    }
    if let Some(e) = x.off {
        v.push(format!("Расчёт «без потолка» сейчас не идёт: {e}."));
    }
    v
}
