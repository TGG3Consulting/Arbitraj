//! Файл: core/sell_loop.rs
//! Что делает: решение 389 (задача t175, авария f9634504 17.11.2026: «thread 'tokio-rt-worker' has overflowed its
//! stack» сразу после core.sell_unsent_here сделки 20261117143812842GENIUS) — продолжения продажи сделки исполняются
//! циклом на одном уровне стека, а не вложенно. Цепочка «продажа → срыв → режим застрявшей монеты / повтор /
//! продажа здесь → снова продажа» (sell.rs ↔ sell_unsent.rs ↔ stuck.rs ↔ relay.rs ↔ relay_here.rs ↔ manual_sell.rs ↔
//! sell_range_run.rs) была async-рекурсией: каждый следующий уровень опрашивался изнутри poll предыдущего, кадры всех
//! уровней лежали на стеке потока одновременно (Box::pin уносит в кучу будущее, но не кадры опроса).
//! Как устроено (батут): продолжение после итога продажи (sell_next.rs собирает его в коробку) отдаётся в `hop`.
//! - В задаче ещё нет цикла — `hop` сам становится циклом (`drive`): исполняет продолжение, затем каждое следующее,
//!   отложенное изнутри него, по очереди, на своём уровне стека.
//! - Цикл уже есть (мы внутри продолжения) — продолжение кладётся в ячейку задачи и `hop` сразу возвращается; все
//!   кадры между циклом и этим местом — хвостовые вызовы (после них по коду ничего не делается, решение 389 — список
//!   в docs/notes/t175-sell-stuck-no-recursion-2026-11-17.md), поэтому порядок шагов, записей журнала, хронологии и
//!   уведомлений тот же: следующее продолжение начинается ровно тогда, когда раньше начинался вложенный вызов.
//!
//! Признаки задачи, которые ставили кадры между циклом и местом откладывания (ручная команда risk_count.rs, терпение
//! после HTTP 429 gateway/patience.rs), запоминаются при откладывании и ставятся заново вокруг продолжения — оно видит
//! те же значения, что видело бы вложенным. Прочие признаки задачи (срочность, ярус счёта и т. п.) ставятся выше
//! цикла и видны ему и так. Отдельная задача tokio (tokio::spawn) не используется: она потеряла бы все признаки задачи
//! и связь отмены. Ячейка занята (двух откладываний подряд без возврата по коду нет) — продолжение исполняется сразу,
//! как раньше (вложенно), ничего не теряется.
//! Кто вызывает: core/sell.rs (продолжения после итога продажи и вход в режим застрявшей монеты), core/sell_range_run.rs.
//! От чего зависит: risk_count.rs (snapshot, restore), gateway/patience.rs (snapshot, restore), tokio (task_local).
//! Настройки: нет (базовое поведение, не выключается).

use std::cell::RefCell;
use std::future::Future;
use std::pin::Pin;

/// Продолжение продажи: владеет всем, что ему нужно (ядро — клоном), в куче.
pub type Job = Pin<Box<dyn Future<Output = ()> + Send + 'static>>;

tokio::task_local! {
    /// Ячейка цикла продолжений задачи: следующее продолжение (None — нет).
    static NEXT: RefCell<Option<Job>>;
}

/// Исполняет продолжение продажи без роста стека (см. шапку). Принимает: продолжение. Возвращает: когда продолжение
/// исполнено (вне цикла — вместе со всеми, что оно отложило) или отложено (внутри цикла). Ошибок нет; паника
/// продолжения — как раньше, наверх по задаче.
pub async fn hop(job: Job) {
    let job = carry(job);
    match NEXT.try_with(|n| n.borrow().is_none()) {
        // Внутри цикла, ячейка свободна — откладываем, цикл исполнит после возврата.
        Ok(true) => NEXT.with(|n| *n.borrow_mut() = Some(job)),
        // Ячейка занята — сразу, вложенно (как до решения 389).
        Ok(false) => job.await,
        // Цикла нет — этот вызов и есть цикл.
        Err(_) => drive(job).await,
    }
}

/// Цикл продолжений: исполняет первое, затем по одному отложенные, пока ячейка не пуста. Принимает: первое
/// продолжение. Ошибок нет.
async fn drive(first: Job) {
    NEXT.scope(RefCell::new(None), async move {
        let mut job = first;
        loop {
            job.await;
            match NEXT.with(|n| n.borrow_mut().take()) {
                Some(next) => job = next,
                None => break,
            }
        }
    })
    .await
}

/// Запоминает признаки задачи, видимые в месте откладывания (ручная команда, терпение после 429), и оборачивает
/// продолжение ими (см. шапку). Не-async — будущее собирается в куче, вне кадра вызывающего. Принимает:
/// продолжение. Возвращает: обёрнутое продолжение. Ошибок нет.
#[inline(never)]
fn carry(job: Job) -> Job {
    let manual = super::risk_count::snapshot();
    let patience = crate::gateway::patience::snapshot();
    Box::pin(async move {
        let job = crate::gateway::patience::restore(patience, job);
        super::risk_count::restore(manual, job).await
    })
}
