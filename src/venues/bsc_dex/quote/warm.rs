//! Файл: venues/bsc_dex/quote/warm.rs
//! Что делает: фоновый прогрев данных узла, нужных расчёту, чтобы расчёт их НИКОГДА не тянул с узла сам (решение 89).
//! На каждый новый блок обновляет цену газа (eth_gasPrice, quote/gas.rs) и время блока (eth_getBlockByNumber,
//! node/heads.rs) в их кэшах. Тогда N параллельных расчётов читают тёплый кэш и не ждут узел. Узел подвис — прогрев
//! повторится на следующем блоке, а расчёт пользуется последним известным значением (gas.rs / heads.rs: при занятом
//! single-flight отдают последнее известное, не блокируясь). Ошибки прогрева игнорируются — это фон, не путь сделки.
//! Кто вызывает: pools/market.rs (фоновая задача при подписке на рынок).
//! От чего зависит: ctx.rs, node/heads.rs, quote/gas.rs.
//! Настройки: нет (ритм — по новым головам, node/heads.rs; цену газа читает send.gas_price_markup_pct внутри gas.rs).

use super::super::ctx::Ctx;
use super::super::node::heads::Heads;
use super::gas::GasPrice;

/// Прогревает цену газа и время блока на каждый новый блок. Работает, пока жив приёмник голов (канал закрыт — выходим).
/// Принимает: окружение, головы сети, цену газа. Ошибок не возвращает (прогрев — фон).
pub async fn run(ctx: Ctx, heads: Heads, gas: GasPrice) {
    let mut rx = heads.watch();
    loop {
        // Ждём новую голову (или первую). Отправитель закрыт — задача завершается.
        if rx.changed().await.is_err() {
            return;
        }
        if rx.borrow().is_none() {
            continue;
        }
        // Прогрев кэшей. Ошибки игнорируем — повторим на следующем блоке, расчёт берёт последнее известное.
        let _ = heads.at(&ctx).await;
        let _ = gas.wei(&ctx, &heads).await;
    }
}
