//! Файл: gateway/tx_hash.rs
//! Что делает: сравнение хешей транзакций из ответов площадок после нормализации (решение 118, Я-16 / А-🟠6):
//! нижний регистр, без префикса «0x», только часть до первого «:».
//! Кто вызывает: адаптеры бирж (venues/bingx/transfers.rs, venues/mexc/transfers.rs) — поиск депозита по хешу.
//! От чего зависит: ничего.
//! Настройки: нет.
//!
//! Зачем: формат хеша в истории депозитов биржи в документации не задан. У MEXC в примере deposit/hisrec
//! (https://www.mexc.com/api-docs/spot-v3/wallet-endpoints/deposit-historysupporting-network) txId без «0x», в истории
//! выводов transHash — с «0x»; у других бирж бывает вид «хеш:индекс». Хеш транзакции BSC — 32 байта в hex (регистр
//! hex незначим), поэтому одна и та же транзакция должна находиться при любом из этих видов.

/// Что делает: приводит хеш к виду для сравнения.
/// Принимает: хеш как его отдала площадка или сеть.
/// Возвращает: нижний регистр, без пробелов по краям, без «0x»/«0X», до первого «:».
/// Ошибки: нет.
pub fn norm(h: &str) -> String {
    let h = h.trim();
    let h = h.split(':').next().unwrap_or_default();
    let h = h
        .strip_prefix("0x")
        .or_else(|| h.strip_prefix("0X"))
        .unwrap_or(h);
    h.to_ascii_lowercase()
}

/// Что делает: та же ли это транзакция.
/// Принимает: два хеша в любом из видов (с «0x» и без, любой регистр, с суффиксом «:индекс»).
/// Возвращает: true — совпали после нормализации; пустой хеш не совпадает ни с чем.
/// Ошибки: нет.
pub fn same(a: &str, b: &str) -> bool {
    let (a, b) = (norm(a), norm(b));
    !a.is_empty() && a == b
}
