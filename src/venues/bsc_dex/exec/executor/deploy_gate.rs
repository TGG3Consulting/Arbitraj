//! Что делает: решение 399 (финальное ревью релиза 17.11, п. 1 и Н2), решение 400 (t185) — запрет развёртывания
//! исполнителя, пока в записи симуляции на живых пулах сети (tests/data/executor_v3_live_<дата>/, вшита в сборку —
//! exec/executor/live_proof.rs) у текущей сборки (v3, contracts/out/) не принят НИ ОДИН класс шага (вид 19 / 20 / 21 ×
//! крючок, + Infinity Stable; правило — live_rule.rs). Принят хотя бы один — развёртывание разрешено; шаги непринятых
//! классов исполнителем всё равно не идут (entry.rs fits / singleton → live_proof::admits). Обходной настройки нет:
//! запрет снимает только запись, по которой правило принимает класс. Здесь же — подсказка для маршрутов и шагов, которым
//! нужен v3: пока v3 не принят, причина без призыва переразвернуть исполнитель (кнопка всё равно откажет).
//! Кто вызывает: exec/executor/deploy.rs (quote — поле warning, deploy — отказ до любой работы с сетью), venue.rs
//! (dex_executor_refusal — экран «Маппинг кошельков»: недоступная кнопка с причиной), exec/executor/onchain.rs (v3_note),
//! pools/exec_callback.rs (step_absent для видов с v3), тесты.
//! От чего зависит: exec/executor/{live_proof, live_rule}.rs.
//! Настройки: нет (факт о собранном коде, не настройка торговли).

use super::live_proof;
use super::live_rule::Verdict;

/// Короткая причина запрета — её же показывает интерфейс у недоступной кнопки «Развернуть исполнитель».
pub const NOT_ACCEPTED: &str = "v3 не принят на живых пулах ни в одном классе шага";

/// Причина запрета развёртывания для текущей сборки. Возвращает: None — разрешено (принят хотя бы один класс); Some —
/// текст отказа с перечнем принятого и непринятого. Ошибок нет.
pub fn refusal() -> Option<String> {
    refusal_for(live_proof::verdicts())
}

/// То же для данных вердиктов (проверяемо тестом). Возвращает: None — принят хотя бы один класс; иначе текст отказа.
/// Ошибок нет.
pub fn refusal_for(v: &Result<Vec<Verdict>, String>) -> Option<String> {
    match v {
        Ok(list) if list.iter().any(|x| x.accepted) => None,
        _ => Some(format!(
            "Развёртывание исполнителя запрещено — {NOT_ACCEPTED}. {}. Обходной настройки нет (решения 395, 399, 400; \
             кошелёк с v2 работает как раньше).",
            live_proof::listing_of(v)
        )),
    }
}

/// Решение 399 (Н2): что делать маршруту или шагу, которому нужен исполнитель v3. Возвращает: пока v3 не принят —
/// «нужен исполнитель v3; v3 ещё не принят на живых пулах» (без призыва переразвернуть: развёртывание запрещено);
/// принят — «переразверните исполнитель кошелька (экран «Маппинг кошельков»)». Ошибок нет.
pub fn need_v3() -> &'static str {
    need_v3_for(refusal().is_some())
}

/// То же при известном запрете (проверяемо тестом). Принимает: запрещено ли развёртывание. Ошибок нет.
pub fn need_v3_for(refused: bool) -> &'static str {
    if refused {
        "нужен исполнитель v3; v3 ещё не принят на живых пулах"
    } else {
        "переразверните исполнитель кошелька (экран «Маппинг кошельков»)"
    }
}
