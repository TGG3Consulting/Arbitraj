//! Файл: core/types/pool_fictive.rs
//! Что делает: состояние пары «с фиктивными резервами и средней ценой» (решение 288) — без названия площадки: резервы
//! пары, фиктивные резервы (по ним формула x·y=k), средняя цена и время её записи (обмен пересчитывает среднюю цену к
//! времени своего блока), комиссии пары и время блока чтения. Вынесено из pool.rs (предел размера файла).
//! Кто вызывает: core/types/pool.rs (PoolState::Fictive), адаптер DEX (pools/load_smardex.rs создаёт, math/smardex.rs
//! считает).
//! От чего зависит: alloy-primitives, serde.
//! Настройки: нет.

use alloy_primitives::U256;
use serde::{Deserialize, Serialize};

/// Состояние пары с фиктивными резервами на блоке — боксируется в `PoolState::Fictive`. Математика — в адаптере.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct FictiveData {
    /// Резерв token0 (баланс пары минус накопленная доля протокола).
    pub reserve0: U256,
    /// Резерв token1.
    pub reserve1: U256,
    /// Фиктивный резерв token0.
    pub fictive0: U256,
    /// Фиктивный резерв token1.
    pub fictive1: U256,
    /// Средняя цена: сторона token0.
    pub price_average0: U256,
    /// Средняя цена: сторона token1.
    pub price_average1: U256,
    /// Время записи средней цены (секунды Unix; 0 — ещё не было обмена).
    pub price_average_ts: u64,
    /// Комиссия поставщикам ликвидности — числитель над основанием комиссий пары.
    pub fees_lp: U256,
    /// Комиссия протокола — числитель над тем же основанием.
    pub fees_pool: U256,
    /// Время блока, на котором прочитано состояние (секунды Unix) — к нему приводится средняя цена в котировке.
    pub block_ts: u64,
}
