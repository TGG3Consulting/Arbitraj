//! Файл: core/deposit_proof_plan.rs
//! Что делает: решение 411 (задача t196) — чистая логика сверки адреса депозита биржи-получателя: (1) свежий ответ биржи
//! против адреса из памяти — совпал, изменился или в памяти не было; (2) какой адрес берёт перевод (вывод на биржу B):
//! только подтверждённый свежим ответом биржи в этой сделке, иначе — свой свежий запрос; (3) тексты журнала и
//! уведомления — без значений адреса и memo (только «изменился»).
//! Кто вызывает: core/deposit_proof.rs, tests/core_deposit_proof_411.rs.
//! От чего зависит: ничего (чистая логика).
//! Настройки: нет.

/// Свежий ответ биржи: адрес или текст ошибки адаптера.
pub type Fresh = Result<String, String>;

/// Итог сверки свежего ответа с памятью.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Seen {
    /// Совпал с адресом в памяти.
    Same,
    /// Другой адрес: память обновлена (адаптер положил свежий), событие в журнал и Telegram.
    Changed,
    /// В памяти адреса не было — сверять не с чем.
    First,
}

/// Что делает: сверка свежего адреса с памятью. Принимает: адрес из памяти (None — не было), свежий адрес.
/// Возвращает: Seen. Ошибок нет.
pub fn compare(memory: Option<&str>, fresh: &str) -> Seen {
    match memory {
        None => Seen::First,
        Some(m) if m == fresh => Seen::Same,
        Some(_) => Seen::Changed,
    }
}

/// Подтверждение адреса, которое перевод нашёл у своей сделки.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum State {
    /// Подтверждения нет (перегон, возврат USDT, ручной перевод — без предпроверки сделки).
    Absent,
    /// Подтверждение другой площадки, монеты или сети, или ключи API сменились после предпроверки.
    Stale,
    /// Свежий ответ предпроверки этой сделки получен (перевод дождался его, если он ещё шёл).
    Done(Fresh),
}

/// Что делать переводу.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Pick {
    /// Вывод — на этот адрес (подтверждён свежим ответом биржи в этой сделке).
    Use(String),
    /// Свой свежий запрос адреса перед выводом (как раньше при промахе памяти); причина — для журнала.
    Ask(String),
}

/// Что делает: какой адрес берёт перевод. Принимает: State. Возвращает: Pick. Ошибок нет.
pub fn for_withdraw(s: State) -> Pick {
    match s {
        State::Done(Ok(a)) => Pick::Use(a),
        State::Done(Err(_)) => Pick::Ask("свежий запрос адреса в предпроверке не удался".into()),
        State::Stale => {
            Pick::Ask("подтверждение предпроверки к этому переводу не относится".into())
        }
        State::Absent => Pick::Ask("подтверждения адреса в этой сделке нет".into()),
    }
}

/// Что делает: брать ли адрес из памяти в предпроверке без ожидания. Принимает: есть ли адрес в памяти, упал ли
/// последний свежий запрос по этому ключу. Возвращает: true — из памяти (свежий запрос идёт фоном). Ошибок нет.
pub fn use_memory(in_memory: bool, last_failed: bool) -> bool {
    in_memory && !last_failed
}

/// Что делает: текст журнала и Telegram «адрес изменился» — без значений адреса и memo. Принимает: площадку, монету,
/// сеть. Возвращает: текст. Ошибок нет.
pub fn changed_text(venue: &str, ticker: &str, net: &str) -> String {
    format!(
        "{venue}: адрес депозита {ticker} в сети {net} изменился — свежий ответ биржи не совпал с адресом в памяти \
         бота. Сделано: память обновлена на адрес из свежего ответа; вывод на {venue} берёт только адрес, \
         подтверждённый свежим ответом биржи в этой сделке, — на старый адрес монеты не уйдут"
    )
}

/// Что делает: текст журнала «свежий запрос не удался, а адрес был в памяти» — без текста адаптера (в нём бывает
/// значение memo/tag). Принимает: площадку, монету, сеть. Возвращает: текст. Ошибок нет.
pub fn failed_text(venue: &str, ticker: &str, net: &str) -> String {
    format!(
        "{venue}: свежий запрос адреса депозита {ticker} в сети {net} не удался — адрес из памяти не \
         подтверждён: вывод сделки запросит адрес заново, следующая предпроверка ждёт ответ биржи"
    )
}
