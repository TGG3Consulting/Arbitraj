//! Файл: venues/bsc_dex/fast_hash.rs
//! Что делает: хеш-карты и множества горячего пути DEX с хешем foldhash вместо SipHash по умолчанию std (решение 410,
//! задача t195; perf 18.11: SipHash 3,2 % времени процесса). Только для карт, где порядок обхода не влияет на
//! результат (поиск по ключу; обход — без зависимости от порядка): граф маршрутов (pools/graph.rs adj — токен → рёбра,
//! порядок рёбер внутри ключа — порядок вставки, хеш на него не влияет), книга глубины (pools/depth_book.rs — поиск по
//! пулу, обход только для пометки всех слотов), посещённые токены и пулы перебора путей и циклов
//! (quote/route_paths.rs, quote/route_best.rs — только «есть ли»). Реестр пулов (registry_index.rs) НЕ переведён: его
//! обход задаёт порядок записей снимка, а значит порядок рёбер графа и путей.
//!
//! Почему не нужен SipHash (защита от подбора столкновений): ключи — адреса токенов и ссылки на пулы (адрес контракта,
//! PoolId) из сети. Пул с заданным адресом может создать кто угодно (CREATE2 — адрес считается заранее), то есть ключи
//! частично под контролем стороннего. foldhash::fast::RandomState берёт случайное зерно процесса и своё зерно на каждую
//! карту (foldhash 0.2.0 src/fast.rs RandomState::default) — столкновения нельзя подобрать заранее, не зная зерна
//! запущенного процесса; FxHash (без зерна) поэтому не взят. Оговорка (ревью 410): foldhash по своему README 0.2.0 —
//! «minimally DoS-resistant»: стойкость к интерактивному атакующему, который изучает поведение долго работающего
//! процесса и восстанавливает зерно, он не заявляет; зерно не криптографическое. Порядок обхода этих карт наружу не
//! выходит (в журнал, интерфейс, расчёт не попадает) — по нему зерно не восстановить.
//! foldhash уже был в Cargo.lock (зависимость hashbrown) — добавлен прямой зависимостью той же версии 0.2.0.
//! Кто вызывает: pools/graph.rs, pools/depth_book.rs, quote/route_paths.rs, quote/route_best.rs.
//! От чего зависит: foldhash.
//! Настройки: нет.

/// Хеш-карта с хешем foldhash (создаётся через `default()`).
pub type FastMap<K, V> = std::collections::HashMap<K, V, foldhash::fast::RandomState>;

/// Хеш-множество с хешем foldhash (создаётся через `default()`).
pub type FastSet<T> = std::collections::HashSet<T, foldhash::fast::RandomState>;
