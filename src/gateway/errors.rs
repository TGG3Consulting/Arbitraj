//! Файл: gateway/errors.rs
//! Что делает: единые коды ошибок шлюза. Каждый адаптер переводит ошибки своей площадки
//! в эти коды; ядро и правила шлюза работают только с ними.
//! Кто вызывает: адаптеры (создают), шлюз и ядро (обрабатывают), интерфейс (показывает).
//! От чего зависит: core/types (VenueId, ChainTx).
//! Настройки: нет.
//!
//! Это стык: новый код добавляется только через запрос на изменение стыка (docs/AGENTS.md).

use serde::{Deserialize, Serialize};

use crate::core::types::{ChainTx, VenueId};

/// Код ошибки шлюза. По нему правила шлюза решают, что делать дальше.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ErrorCode {
    /// Ключ или подпись не приняты площадкой.
    InvalidCredentials,
    /// У ключа нет нужного права (торговля, вывод).
    InsufficientPermissions,
    /// IP сервера не в белом списке ключа.
    IpNotAllowed,
    /// Площадка не ответила за отведённое время.
    Timeout,
    /// Нет связи с площадкой (DNS, TCP, TLS).
    Unreachable,
    /// Адрес отклонён (не в белом списке, неверный формат).
    InvalidAddress,
    /// Решение 253, дополнение t82 (Тигран 10.11): операция (вывод) отклонена из-за состояния АККАУНТА на площадке —
    /// вход, 2FA, пароль, верификация, блокировка вывода, лимит вывода аккаунта; не монета и не адрес. Ставит адаптер
    /// только по коду из официальной таблицы ошибок площадки (по умолчанию ни одна площадка его не отдаёт). Ядро — как
    /// InvalidAddress: вывод не повторяется, пауза не ставится, монета не закрывается, алерт venue.account_problem.
    AccountRestricted,
    /// Решение 253, дополнение t85 (Тигран 11.11): вывод отклонён, потому что исчерпан лимит вывода АККАУНТА, который
    /// сбрасывается сам (суточный / месячный — по официальной таблице ошибок площадки; время сброса биржа не сообщает).
    /// Ставит адаптер только у вывода (по умолчанию ни одна площадка его не отдаёт). Ядро: отказ вывода (без повтора по
    /// правилу, не ошибка подряд), монета не закрывается; площадка — на паузу (core/withdraw_limit_pause.rs; снимает
    /// только человек «Снять паузу»), алерт venue.withdraw_limit.
    WithdrawLimit,
    /// Превышен лимит запросов площадки.
    RateLimited,
    /// Нужная настройка не задана в интерфейсе.
    NotConfigured,
    /// Секреты не разблокированы паролем.
    SecretsLocked,
    /// Не хватает средств.
    InsufficientBalance,
    /// Ордер отклонён площадкой.
    OrderRejected,
    /// Решение 268 (Тигран 14.11): ЛИМИТНЫЙ ордер отклонён, потому что его цена вне диапазона, разрешённого биржей
    /// (коридор от цены последней сделки / индексной цены, «price protection»); ордер не принят, деньги не тронуты.
    /// Ставит адаптер биржи только по коду из её официальной документации или живого ответа (venues/<биржа>/errors.rs;
    /// по умолчанию ни одна площадка его не отдаёт); рыночный ордер этот код не отдаёт никогда. Ядро: у продажи сделки —
    /// свежий стакан и то же условие продажи; выполнено — рыночный ордер (core/sell_range.rs,
    /// sell.market_on_price_range); иначе — как OrderRejected. По правилу шлюза не повторяется (своего правила нет —
    /// действует правило OrderRejected), ошибкой площадки подряд не считается.
    PriceOutOfRange,
    /// Ордер отправлен, но не исполнился.
    OrderNotFilled,
    /// Ордер исполнился частично.
    PartialFill,
    /// Вывод отклонён площадкой.
    WithdrawRejected,
    /// Решение 166: вывод отклонён, потому что средства временно заблокированы для вывода (удержание депозита: MEXC
    /// 16021, KuCoin 115008, Binance −4060, Bybit 131085). Вывод не создан — повтор безопасен (core/transfer_locked.rs).
    WithdrawLocked,
    /// Депозит не зачислен за отведённое время.
    DepositNotCredited,
    /// Транзакция свопа в сети откатилась.
    SwapReverted,
    /// Данные устарели — торговать нельзя.
    StaleData,
    /// Адаптер площадки не подключён.
    VenueNotConnected,
    /// Ответ площадки не удалось разобрать.
    BadResponse,
    /// Функция контракта к этой площадке не применима (например, проверка налогов токена у биржи).
    NotApplicable,
    /// Налог монеты или влияние крючка ещё не проверены — торговли нет (решения 30, 32).
    CoinNotChecked,
    /// Проверка монеты или пула не прошла (пробный обмен откатился, узел вернул ошибку) — чёрный список.
    CoinCheckFailed,
    /// Нет допустимого пула или маршрута для монеты (выключены, ликвидность ниже порога, крючок не допущен).
    NoRoute,
    /// Проверка перед отправкой (квотер / eth_call) разошлась с расчётом больше допуска — сделки нет.
    QuoteMismatch,
    /// Канал отправки не принял транзакцию (ответ-ошибка канала, лимит запросов канала).
    ChannelRejected,
    /// Цена газа ниже минимума канала (настройка или ответ канала «require GasPrice»).
    GasBelowChannelMin,
    /// Транзакция не попала в блок за отведённое время (deadline / send.max_wait_blocks).
    TxNotIncluded,
    /// Nonce неверный или занят другой транзакцией (nonce too low).
    NonceConflict,
    /// Транзакция ушла в сеть, а её исход не установлен (nonce занят, своей квитанции нет; квитанция есть, а суммы не
    /// разобраны; лимиты отмены или ожидания исчерпаны). Повторять нельзя — только ручная проверка: ядро не повторяет
    /// операцию по этому коду при любых правилах шлюза и ставит площадку на паузу.
    OutcomeUnknown,
    /// Решение 231 (дополнение, Тигран 08.11): транзакция НЕ подписана и НЕ отправлена — очередь кошелька DEX
    /// остановлена до ручной проверки (venues/bsc_dex/wallet/nonce.rs acquire). Окончательно «не исполнено»: обычная
    /// логика повтора / отказа по правилам шлюза, без паузы «исход неизвестен» (раньше — OutcomeUnknown).
    QueueHalted,
    /// Внутренняя ошибка нашего кода.
    Internal,
}

/// Ошибка шлюза: код, площадка, понятное сообщение, сырой ответ площадки и — если транзакция
/// уже ушла в сеть — её факт (газ потрачен даже при ошибке, решение 36).
#[derive(Debug, Clone, Serialize, Deserialize, thiserror::Error)]
#[error("{code:?} ({venue:?}): {message}")]
pub struct GatewayError {
    pub code: ErrorCode,
    /// Площадка; None — ошибка не связана с конкретной площадкой.
    pub venue: Option<VenueId>,
    /// Понятная причина по-русски — её видит Тигран в интерфейсе и Telegram.
    pub message: String,
    /// Сырой ответ площадки (без секретов) для разбора. Box<str> — ошибка остаётся маленькой (решение 236, дополнение:
    /// место под approve_gas_bnb без роста размера; в JSON — та же строка).
    pub raw: Option<Box<str>>,
    /// Транзакция в сети, если ошибка случилась после отправки (откат, не попала в блок).
    /// В коробке, чтобы ошибка оставалась маленькой (она возвращается из множества функций).
    pub tx: Option<Box<ChainTx>>,
    /// «Не задана настройка»: её имя (ставится там, где ошибка создаётся, — settings/read.rs, read_scope.rs и места с
    /// проверкой значения). По нему пул, брошенный из-за настройки, возвращается в чтение, когда её зададут (решение 63).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub setting: Option<String>,
    /// Решение 231: у «исход неизвестен» — чем найти операцию (свой ID ордера или вывода, ID площадки, хеш и nonce
    /// транзакции; gateway/pending.rs). Ставит адаптер; ядро выясняет по нему исход (core/outcome_resolve.rs).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pending: Option<Box<super::pending::PendingRef>>,
    /// Решение 236, дополнение (техлид 09.11): газ разрешений (approve), уже в блоке до этой ошибки обмена, BNB. Деньги
    /// потрачены, хотя обмен не состоялся (или исход выясняется). Не факт транзакции обмена — поле tx не трогает
    /// (OpError.sent по нему не меняется). Ставит адаптер DEX; ядро — в затраты сделки (core/deal_gas.rs). В коробке —
    /// ошибка остаётся маленькой (как tx). Читать — approve_gas().
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub approve_gas_bnb: Option<Box<rust_decimal::Decimal>>,
}

impl GatewayError {
    /// Решение 268: ошибка РЫНОЧНОГО ордера никогда не несёт код PriceOutOfRange (иначе ядро повторяло бы по кругу) —
    /// он заменяется на OrderRejected, текст и сырой ответ те же. Зовёт адаптер на пути рыночной продажи и при ответе
    /// HTTP 5XX (дополнение, ревью 2), ядро — на пути рыночного ордера (trade_ops.rs: и найденный исход). Ошибок нет.
    pub fn no_price_range(mut self) -> Self {
        if self.code == ErrorCode::PriceOutOfRange {
            self.code = ErrorCode::OrderRejected;
        }
        self
    }

    /// Создаёт ошибку.
    /// Принимает: код, площадку (или None), сообщение.
    /// Возвращает: GatewayError без сырого ответа.
    pub fn new(code: ErrorCode, venue: Option<VenueId>, message: impl Into<String>) -> Self {
        Self {
            code,
            venue,
            message: message.into(),
            raw: None,
            tx: None,
            setting: None,
            pending: None,
            approve_gas_bnb: None,
        }
    }

    /// Ошибка «не задана настройка» с её именем. Принимает: имя настройки, текст. Возвращает: NotConfigured.
    pub fn not_set(venue: Option<VenueId>, name: &str, message: impl Into<String>) -> Self {
        let mut e = Self::new(ErrorCode::NotConfigured, venue, message);
        e.setting = Some(name.to_string());
        e
    }

    /// Добавляет факт транзакции в сети.
    /// Принимает: транзакцию. Возвращает: ту же ошибку с полем tx.
    pub fn with_tx(mut self, tx: ChainTx) -> Self {
        self.tx = Some(Box::new(tx));
        self
    }

    /// Решение 236, дополнение: газ разрешений (approve), отправленных до ошибки (см. поле). Принимает: газ BNB (None —
    /// разрешений не было: поле не меняется). Возвращает: ту же ошибку. Ошибок нет.
    pub fn with_approve_gas(mut self, gas: Option<rust_decimal::Decimal>) -> Self {
        if let Some(g) = gas {
            self.approve_gas_bnb = Some(Box::new(g));
        }
        self
    }

    /// Решение 236, дополнение: газ разрешений до ошибки (BNB; None — не было). Ошибок нет.
    pub fn approve_gas(&self) -> Option<rust_decimal::Decimal> {
        self.approve_gas_bnb.as_deref().copied()
    }

    /// Добавляет сырой ответ площадки.
    /// Принимает: текст ответа. Возвращает: ту же ошибку с полем raw.
    pub fn with_raw(mut self, raw: impl Into<String>) -> Self {
        self.raw = Some(raw.into().into_boxed_str());
        self
    }
}

/// Результат операций шлюза.
pub type GatewayResult<T> = Result<T, GatewayError>;
