//! Файл: gateway/feed_health.rs
//! Что делает: решение 202 (Тигран, 06.11.2026: «переподписка не биржи, а именно пачки») — типы стыка «сторож пар»:
//! снимок свежести потока стаканов адаптера по соединениям (пачкам пар) и команды «переподписать пару» /
//! «переподключить соединение». Ядро (core/feed_watch.rs) решает по сделкам и счётчикам; адаптер только отдаёт
//! свежесть и выполняет команду. Общий для адаптеров учёт свежести — gateway/feed_reg.rs.
//! Решение 213 (Тигран, 07.11.2026: «тишина пары ≠ смерть»): версия стакана пары на бирже по REST (BookVersion,
//! метод контракта book_version) и версия последнего кадра пары (PairHealth.last_id / last_changed_ms) — ядро
//! сравнивает их и решает: пара тихая и подтверждена (не переподписывать, стакан свежий до следующей проверки) или
//! кадры потеряны (переподписка по решению 202). Правила сравнения — core/feed_confirm.rs (verdict).
//! Подтверждение по содержимому (Тигран 08.11, задача 213 п. 4): биржа без связи номеров кадра и REST отдаёт в
//! BookVersion.print отпечатки — первые N уровней ответа REST и своего стакана в памяти; равны — тихая, подтверждена;
//! не равны — кадры потеряны (core/feed_print.rs).
//! Кто вызывает: gateway/contract.rs (методы feed_health, resubscribe_pair, reconnect_conn, book_version,
//! book_confirmed), gateway/feed_reg.rs, core/feed_watch.rs, core/feed_confirm.rs, core/feed_print.rs, адаптеры
//! (mexc/book_print.rs, bitget/book_print.rs).
//! От чего зависит: core/types (PriceLevel).
//! Настройки: нет (пороги сторожа — core/feed_watch.rs).

/// Свежесть одной пары соединения (unix мс, часы бота).
#[derive(Debug, Clone, PartialEq)]
pub struct PairHealth {
    /// Тикер ПЛОЩАДКИ (решение 211: тот, под которым адаптер подписан, core/venue_ticker.rs on_venue / ticker_on).
    pub ticker: String,
    /// Последний кадр стакана пары (время приёма ботом); None — с начала соединения кадров не было.
    pub last_ms: Option<i64>,
    /// Когда пара (пере)подписана — с этого момента идёт прогрев (часы бота).
    pub since_ms: i64,
    /// Решение 213: номер версии книги из последнего кадра (тот же счётчик, что BookVersion.id той же биржи — так
    /// должно быть по документации биржи, иначе None). Gate: lastUpdateId кадра spot.order_book. None — кадров не было
    /// или биржа номера в кадре не даёт.
    pub last_id: Option<i64>,
    /// Решение 213: время изменения книги из последнего кадра — по ЧАСАМ БИРЖИ, та же шкала, что
    /// BookVersion.changed_ms (только если документация биржи так определяет поле кадра). None — нет такого поля.
    pub last_changed_ms: Option<i64>,
}

/// Свежесть одного соединения (пачки пар).
#[derive(Debug, Clone, PartialEq)]
pub struct ConnHealth {
    /// Имя соединения адаптера («market-3»).
    pub conn: String,
    /// Последний кадр соединения любого вида (стакан, понг, ответ); None — сессии ещё нет.
    pub alive_ms: Option<i64>,
    /// Начало текущей сессии соединения (подключение) — прогрев.
    pub started_ms: Option<i64>,
    pub pairs: Vec<PairHealth>,
}

/// Снимок свежести потока стаканов площадки.
#[derive(Debug, Clone, PartialEq)]
pub struct FeedHealth {
    /// По документации площадки кадры стакана приходят по расписанию даже без изменений. Решение 213: поле больше
    /// НЕ выключает сторож. Нужно только адаптеру без подтверждения по REST (confirm = false): true — тишина пары =
    /// мёртвая подписка, переподписка по решению 202; false — тихая пара только пишется в журнал (раз), вслепую не
    /// переподписывается. Ставить true только по прямой фразе документации, не по догадке.
    pub scheduled: bool,
    /// Можно переподписать одну пару без обрыва соединения (отписка + подписка в документации канала).
    pub per_pair: bool,
    /// Решение 213: адаптер умеет book_version (версия стакана пары по REST) и book_confirmed (стакан подтверждённой
    /// тихой пары считается свежим в его котировке до указанного момента).
    pub confirm: bool,
    pub conns: Vec<ConnHealth>,
}

/// Решение 213: версия стакана пары на бирже, полученная по REST в момент запроса. Общая для всех бирж: адаптер
/// заполняет то, что даёт его биржа по документации, остальное — None.
/// - `id` — номер версии книги, который растёт при каждом изменении книги и стоит на той же шкале, что номер в кадрах
///   WebSocket (PairHealth.last_id). Gate: поле `id` ответа GET /spot/order_book?with_id=true; Binance-подобные —
///   `lastUpdateId`.
/// - `changed_ms` — когда книга последний раз менялась, unix мс по часам биржи. Gate: поле `update`.
/// - `server_ms` — когда биржа сформировала ответ, unix мс по часам биржи. Gate: поле `current`. Вместе с
///   `changed_ms` даёт «возраст книги» без сравнения часов бота и биржи.
/// - `print` — подтверждение ПО СОДЕРЖИМОМУ (Тигран 08.11: «запросили стакан по REST, сравнили с нашими данными»):
///   для бирж, у которых документация не связывает номер кадра WebSocket с номером REST (MEXC, Bitget). Адаптер
///   кладёт сюда первые N уровней ответа REST и первые N уровней своего стакана в памяти (того, по которому считается
///   котировка), взятые ПОСЛЕ ответа. None — адаптер подтверждает по номеру/времени (Gate).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct BookVersion {
    pub id: Option<i64>,
    pub changed_ms: Option<i64>,
    pub server_ms: Option<i64>,
    pub print: Option<BookPrints>,
}

/// Отпечаток содержимого стакана: первые N уровней обеих сторон от лучшей цены (цена, количество — десятичные,
/// сравнение точное, без допусков; rust_decimal сравнивает значения, «1.10» = «1.1»).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct BookPrint {
    pub bids: Vec<crate::core::types::PriceLevel>,
    pub asks: Vec<crate::core::types::PriceLevel>,
}

impl BookPrint {
    /// Первые n уровней каждой стороны (уровни уже от лучшей цены к худшей: покупатели по убыванию, продавцы по
    /// возрастанию цены). Принимает: уровни, n. Ошибок нет.
    pub fn top(
        bids: &[crate::core::types::PriceLevel],
        asks: &[crate::core::types::PriceLevel],
        n: usize,
    ) -> Self {
        BookPrint {
            bids: bids.iter().take(n).cloned().collect(),
            asks: asks.iter().take(n).cloned().collect(),
        }
    }
}

/// Пара отпечатков для сравнения по содержимому (core/feed_print.rs).
#[derive(Debug, Clone, PartialEq)]
pub struct BookPrints {
    /// Сколько уровней сравнивается (N — venue.depth_levels площадки: столько даёт кадр стакана и столько запрошено у
    /// REST).
    pub levels: usize,
    /// Первые N уровней ответа REST.
    pub rest: BookPrint,
    /// Первые N уровней стакана в памяти адаптера; None — стакана пары в памяти нет.
    pub ours: Option<BookPrint>,
}

/// Команда соединению.
#[derive(Debug, Clone, PartialEq)]
pub enum Cmd {
    /// Переподписать одну пару (тикер площадки).
    Resub(String),
    /// Переподключить соединение с теми же парами.
    Reconnect,
}
