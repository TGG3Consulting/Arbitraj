//! Файл: tests/bsc_dex_math.rs
//! Что делает: проверка точной математики пулов адаптера DEX на официальных тестовых значениях протоколов
//! (тесты v4-core и v3-core — числа заданы в самих тестах явно). Узел BSC из песочницы разработки недоступен,
//! поэтому реальные ответы узла в tests/data/bsc_dex/ пока не записаны.
//! Кто вызывает: cargo test.
//! От чего зависит: arb::venues::bsc_dex::math.

use alloy_primitives::{I256, U256};
use arb::venues::bsc_dex::math::swap_step::{step_v3, step_v4};

/// Число из десятичной строки.
fn u(s: &str) -> U256 {
    U256::from_str_radix(s, 10).unwrap()
}
/// Знаковое число I256.
fn i(v: i128) -> I256 {
    I256::try_from(v).unwrap()
}
const P11: &str = "79228162514264337593543950336";
const P101_100: &str = "79623317895830914510639640423";
const P1000_100: &str = "250541448375047931186413801569";
const P10000_100: &str = "792281625142643375935439503360";
const E18: i128 = 1_000_000_000_000_000_000;

/// Официальные тесты v4-core test/libraries/SwapMath.t.sol#L23-L178 (коммит bea7f6d1).
#[test]
fn official_v4() {
    let r = step_v4(u(P11), u(P101_100), 2 * E18 as u128, i(-E18), 600).unwrap();
    assert_eq!(
        (r.1, r.2, r.3),
        (
            u("9975124224178055"),
            u("9925619580021728"),
            u("5988667735148")
        )
    );
    let r = step_v4(u(P11), u(P101_100), 2 * E18 as u128, i(E18), 600).unwrap();
    assert_eq!(
        (r.1, r.2, r.3),
        (
            u("9975124224178055"),
            u("9925619580021728"),
            u("5988667735148")
        )
    );
    let r = step_v4(u(P11), u(P1000_100), 2 * E18 as u128, i(-E18), 600).unwrap();
    assert_eq!(
        (r.1, r.2, r.3),
        (
            u("999400000000000000"),
            u("666399946655997866"),
            u("600000000000000")
        )
    );
    let r = step_v4(u(P11), u(P10000_100), 2 * E18 as u128, i(E18), 600).unwrap();
    assert_eq!(
        (r.1, r.2, r.3),
        (
            u("2000000000000000000"),
            u(&E18.to_string()),
            u("1200720432259356")
        )
    );
    let r = step_v4(
        u("417332158212080721273783715441582"),
        u("1452870262520218020823638996"),
        159344665391607089467575320103,
        i(1),
        1,
    )
    .unwrap();
    assert_eq!(
        r,
        (
            u("417332158212080721273783715441581"),
            u("1"),
            u("1"),
            u("1")
        )
    );
    let r = step_v4(u("2"), u("1"), 1, i(-3915081100057732413702495386755767), 1).unwrap();
    assert_eq!(
        r,
        (
            u("1"),
            u("39614081257132168796771975168"),
            U256::ZERO,
            u("39614120871253040049813")
        )
    );
    let r = step_v4(
        u("2413"),
        u("79887613182836312"),
        1985041575832132834610021537970,
        i(-10),
        1872,
    )
    .unwrap();
    assert_eq!(r, (u("2413"), u("9"), U256::ZERO, u("1")));
    let p = u("20282409603651670423947251286016");
    let r = step_v4(p, p * U256::from(11u8) / U256::from(10u8), 1024, i(4), 3000).unwrap();
    assert_eq!((r.1, r.2, r.3), (u("26215"), U256::ZERO, u("79")));
    let r = step_v4(
        p,
        p * U256::from(9u8) / U256::from(10u8),
        1024,
        i(263000),
        3000,
    )
    .unwrap();
    assert_eq!((r.1, r.2, r.3), (u("1"), u("26214"), u("1")));
}

/// Официальные тесты v3-core test/SwapMath.spec.ts#L148-L230 (коммит 5ea68a77) — числа заданы явно;
/// у V3 точный вход — положительная сумма, точный выход — отрицательная.
#[test]
fn official_v3() {
    let r = step_v3(
        u("417332158212080721273783715441582"),
        u("1452870262520218020823638996"),
        159344665391607089467575320103,
        i(-1),
        1,
    )
    .unwrap();
    assert_eq!(
        r,
        (
            u("417332158212080721273783715441581"),
            u("1"),
            u("1"),
            u("1")
        )
    );
    let r = step_v3(u("2"), u("1"), 1, i(3915081100057732413702495386755767), 1).unwrap();
    assert_eq!(
        r,
        (
            u("1"),
            u("39614081257132168796771975168"),
            U256::ZERO,
            u("39614120871253040049813")
        )
    );
    let r = step_v3(
        u("2413"),
        u("79887613182836312"),
        1985041575832132834610021537970,
        i(10),
        1872,
    )
    .unwrap();
    assert_eq!(r, (u("2413"), U256::ZERO, U256::ZERO, u("10")));
    let p = u("20282409603651670423947251286016");
    let r = step_v3(
        p,
        p * U256::from(11u8) / U256::from(10u8),
        1024,
        i(-4),
        3000,
    )
    .unwrap();
    assert_eq!((r.1, r.2, r.3), (u("26215"), U256::ZERO, u("79")));
    let r = step_v3(
        p,
        p * U256::from(9u8) / U256::from(10u8),
        1024,
        i(-263000),
        3000,
    )
    .unwrap();
    assert_eq!((r.1, r.2, r.3), (u("1"), u("26214"), u("1")));
}

/// Официальные тесты v2-periphery test/UniswapV2Router02.spec.ts#L54-L76 (коммит ed249913), комиссия 0,3%:
/// getAmountOut(2, 100, 100) = 1, getAmountIn(1, 100, 100) = 2, нули — откат.
#[test]
fn official_v2() {
    use arb::venues::bsc_dex::math::v2::{amount_in, amount_out, fee_ratio};
    use std::str::FromStr;
    let fee = fee_ratio(rust_decimal::Decimal::from_str("0.3").unwrap()).unwrap();
    let n = |v: u64| U256::from(v);
    assert_eq!(amount_out(n(2), n(100), n(100), fee), Some(n(1)));
    assert_eq!(amount_in(n(1), n(100), n(100), fee), Some(n(2)));
    assert_eq!(amount_out(n(0), n(100), n(100), fee), None);
    assert_eq!(amount_out(n(2), n(0), n(100), fee), None);
    assert_eq!(amount_in(n(1), n(100), n(0), fee), None);
}
