//! Файл: core/types/presell.rs
//! Что делает: итог симуляции продажи DEX ДО покупки (решение 234; живой случай ASS 08.11 — план с налогом продажи
//! 3.166 %, а каждая продажа откатывалась «minOut»): продажа собрана тем путём исполнения, которым пойдёт настоящая
//! (прямой / умный / бандл / исполнитель), кошельком сделки по маппингу, на ожидаемый приход, с тем же минимумом
//! выхода, и прогнана eth_simulateV1. Выход — после реального налога токена; по нему ядро пересчитывает выгодность.
//! Кто вызывает: адаптер DEX (заполняет — Venue::dex_presell), core/precheck_dex_sell.rs (пересчёт и журнал).
//! От чего зависит: rust_decimal, serde.
//! Настройки: нет.
//!
//! Это стык: менять только через запрос на изменение стыка (docs/AGENTS.md).

use rust_decimal::Decimal;
use serde::{Deserialize, Serialize};

/// Итог удачной симуляции продажи DEX (откат и любой отказ — ошибка контракта с причиной).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DexPresell {
    /// Кошелёк, от имени которого шла симуляция (0x…).
    pub wallet: String,
    /// Форма исполнения: «прямой», «умный», «граф: бандл», «… → исполнитель …».
    pub form: String,
    /// Блок, поверх которого шла симуляция.
    pub block: u64,
    /// Монет продано по живому пересчёту маршрута.
    pub coins: Decimal,
    /// USDT получено кошельком в симуляции (баланс после − до): после реального налога токена и всех пулов.
    pub out: Decimal,
    /// USDT ожидалось по живому пересчёту маршрута (модельный налог).
    pub expected: Decimal,
    /// Минимум выхода каждой доли (USDT), как в настоящей сделке (exec/leg_min.rs).
    pub min_legs: Vec<Decimal>,
    /// Как монеты оказались у кошелька в симуляции (баланс кошелька или перевод из пула-источника).
    pub funding: Option<String>,
    /// Газ обмена в симуляции.
    pub gas_swap: u64,
}
