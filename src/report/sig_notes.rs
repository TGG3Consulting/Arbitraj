//! Файл: report/sig_notes.rs
//! Что делает: решение 255 — лист «Пояснения» книги «Сигналы и сделки»: период, время выгрузки, что такое сигнал по
//! коду, откуда каждая колонка, правило привязки сделок, что сейчас не пишется (по настройкам на момент выгрузки).
//! Кто вызывает: report/mod.rs (signals_files).
//! От чего зависит: core/signals_src.rs, sig_model.rs.
//! Настройки: нет (window.*, episode.*, window.dex_pool_state — только причины из SignalsSrc).

use crate::core::signals_src::SignalsSrc;

use super::sig_model::ts;

/// Что делает: строки «Пояснений». Принимает: данные, подпись периода. Ошибок нет.
pub fn notes(src: &SignalsSrc, period: &str) -> Vec<String> {
    let mut v = vec![
        format!("Отчёт «Сигналы и сделки» — {period}; выгружен {} UTC. Всё время — UTC.", ts(src.now)),
        "Сигнал = окно бота (решение 125): открывается, когда направление монеты (биржа покупки → биржа продажи) прошло \
         расчёт прибыльности с порогами money.min_profit_usd / pct; держит все направления той же монеты; закрывается \
         после window.min_hold_ms без прохода и после конца нашей сделки. Строка листа «Сигналы» — одно направление окна: \
         «Биржа 1» — где покупаем, «Биржа 2» — где продаём. Ключ сигнала — id окна (на объёмных листах — столбец \
         «Ключ сигнала»)."
            .into(),
        "Начало / конец сигнального окна — время открытия и закрытия окна (таблица windows). Окна, удалённые уборкой \
         (window.keep_days, window.max_mb), удалены вместе со строкой — их в отчёте нет."
            .into(),
        "Сделка привязана к окну: 1) по списку сделок окна (сделки той же монеты, начатые, пока окно открыто); 2) иначе — \
         окно той же монеты (адрес контракта), где было направление сделки, и старт сделки внутри окна; 3) иначе — своя \
         строка с ключом «сделка <id>» и причиной, почему окна нет."
            .into(),
        "Время трейда на бирже 1 — завершение покупки (TradeResult.finished_at), на бирже 2 — завершение каждой продажи \
         (продажа не на бирже 2 — с её площадкой). Размер — количество монеты / сумма USDT (количество × средняя цена)."
            .into(),
        "Тики — лента сделок биржи из файла окна (кадры Trades, разбирает адаптер биржи). У DEX ленты сделок пула в окне \
         нет: события Swap в окно не пишутся (есть только в сыром журнале узла raw/bsc_dex при raw.enabled = да и \
         подписке WebSocket)."
            .into(),
        "Стаканы — кадры файла окна: снимок N уровней торгового потока (по нему бот котировал) и стакан всей глубины по \
         изменениям (полный + изменения по правилам версий); у биржи без стакана в окне — верхние уровни из записей эпизода. \
         Сами уровни не выводятся (их тысячи) — лучший bid / ask, число уровней, сумма цена × количество по уровням кадра; \
         уровни целиком — в файле окна (экран «Окна» → «Скачать файл»)."
            .into(),
        "Ликвидность пула — точки цены DEX окна (window.dex_price: средняя цена на объём тика или нашей сделки, блок, пулы \
         маршрута), состояние пулов маршрута в точке (window.dex_pool_state, решение 255), состояние пулов и глубина пулов \
         из записей эпизодов направления, пересекающихся с окном (episode.*). Числа состояния (резервы, sqrtPriceX96, \
         ликвидность) — в единицах контракта, десятичными."
            .into(),
    ];
    let off = [
        ("Окна сейчас не пишутся", &src.windows_off),
        ("Эпизоды сейчас не пишутся", &src.episodes_off),
        (
            "Состояние пулов в точках DEX сейчас не пишется",
            &src.pool_state_off,
        ),
    ];
    for (what, why) in off {
        if let Some(w) = why {
            v.push(format!("{what}: {w}."));
        }
    }
    v
}
