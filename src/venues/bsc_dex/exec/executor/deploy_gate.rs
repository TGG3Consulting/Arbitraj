//! Файл: venues/bsc_dex/exec/executor/deploy_gate.rs
//! Что делает: решение 399 (финальное ревью релиза 17.11, п. 1 и Н2) — запрет развёртывания исполнителя, пока текущая
//! сборка (v3, contracts/out/) не принята на живых пулах сети: SHA-256 текущего bin-runtime не равен code::LIVE_PROOF
//! (или LIVE_PROOF не задан). Обходной настройки нет: запрет снимает только новая сборка, в которой LIVE_PROOF = SHA
//! записи симуляции (tests/data/executor_v3_live_<дата>/, процедура — docs/notes/t181-executor-all-kinds-2026-11-17.md,
//! п. 5). Здесь же — подсказка для маршрутов и шагов, которым нужен v3: пока v3 не принят, причина без призыва
//! переразвернуть исполнитель (кнопка всё равно откажет).
//! Кто вызывает: exec/executor/deploy.rs (quote — поле warning, deploy — отказ до любой работы с сетью), venue.rs
//! (dex_executor_refusal — экран «Маппинг кошельков»: недоступная кнопка с причиной), exec/executor/onchain.rs (v3_note),
//! pools/exec_callback.rs (step_absent для видов с v3), тесты.
//! От чего зависит: exec/executor/code.rs (LIVE_PROOF, live_warning_for, live_warning).
//! Настройки: нет (факт о собранном коде, не настройка торговли).

use super::code;

/// Короткая причина запрета — её же показывает интерфейс у недоступной кнопки «Развернуть исполнитель».
pub const NOT_ACCEPTED: &str = "v3 не принят на живых пулах: нужна запись симуляции";

/// Причина запрета развёртывания для текущей сборки. Возвращает: None — разрешено (LIVE_PROOF = SHA-256 текущего
/// bin-runtime); Some — текст отказа. Ошибок нет.
pub fn refusal() -> Option<String> {
    code::live_warning().map(|w| text(&w))
}

/// То же для данных значений (проверяемо тестом). Принимает: SHA-256 из записи симуляции (LIVE_PROOF), SHA-256 текущего
/// bin-runtime. Возвращает: None — совпали; иначе текст отказа. Ошибок нет.
pub fn refusal_for(proof: Option<&str>, current: Option<&str>) -> Option<String> {
    code::live_warning_for(proof, current).map(|w| text(&w))
}

/// Текст отказа: короткая причина и подробность (какая запись, какой код). Ошибок нет.
fn text(detail: &str) -> String {
    format!("Развёртывание исполнителя запрещено — {NOT_ACCEPTED}. {detail}")
}

/// Решение 399 (Н2): что делать маршруту или шагу, которому нужен исполнитель v3. Возвращает: пока v3 не принят —
/// «нужен исполнитель v3; v3 ещё не принят на живых пулах» (без призыва переразвернуть: развёртывание запрещено);
/// принят — «переразверните исполнитель кошелька (экран «Маппинг кошельков»)». Ошибок нет.
pub fn need_v3() -> &'static str {
    need_v3_for(refusal().is_some())
}

/// То же при известном запрете (проверяемо тестом). Принимает: запрещено ли развёртывание. Ошибок нет.
pub fn need_v3_for(refused: bool) -> &'static str {
    if refused {
        "нужен исполнитель v3; v3 ещё не принят на живых пулах"
    } else {
        "переразверните исполнитель кошелька (экран «Маппинг кошельков»)"
    }
}
