//! Файл: core/manual_wait_text.rs
//! Что делает: решение 405 (t191, требование Тиграна 18.11: тексты — чётко и конкретно, человеческими словами) —
//! тексты ожидания ручной кнопки (manual_wait.rs, manual_wait_pause.rs, manual_wait_run.rs): что нажато и кем, какую
//! монету и какие сделки ждём (ID, монета, откуда → куда, шаг, сколько монет и где — deal_words.rs), что бот делает
//! сейчас и что сделать человеку (какая кнопка и где). Журнал core.manual_wait, ответ кнопки (экран, Telegram), отказ
//! входа сделки (журнал core.start_refused).
//! Кто вызывает: manual_wait.rs, manual_wait_pause.rs, manual_wait_run.rs.
//! От чего зависит: manual_wait.rs (ManualWait).
//! Настройки: нет.

use super::manual_wait::ManualWait;

/// Держащая сделка застряла: «монету держит сделка … — она застряла …». Принимает: слова сделки. Ошибок нет.
pub fn stuck(deal: &str) -> String {
    format!(
        "монету держит {deal} — она застряла, окончания не будет (её ведёт режим застрявшей монеты)"
    )
}

/// Отказ кнопки сразу: держащая застряла. Принимает: кнопку, монету, причину (stuck). Ошибок нет.
pub fn refused(what: &str, coin: &str, why: &str) -> String {
    format!(
        "«{what}» по {coin} не выполнено: {why}. Что сделать: дождитесь, пока бот разберёт эту сделку, или решите её на \
         экране «Ручное управление», когда она там появится; потом нажмите «{what}» снова (решение 405)"
    )
}

/// Ответ кнопки: ожидание начато. Принимает: ожидание. Ошибок нет.
pub fn started(w: &ManualWait) -> String {
    format!(
        "«{}» по {} (нажал: {}) ждёт окончания сделок по {}: {}. Пока ждём, новые сделки {} не начинаются. Когда эти \
         сделки закончатся, бот сам выполнит «{}». Отменить — кнопка «Отменить ожидание» на экране «Ручное управление»",
        w.what,
        w.coin,
        w.who,
        w.coin,
        w.waits_for.join("; "),
        w.coin,
        w.what
    )
}

/// Отказ второй кнопки по той же монете. Принимает: новую кнопку, монету, уже ждущее. Ошибок нет.
pub fn already(what: &str, coin: &str, x: &ManualWait) -> String {
    format!(
        "«{what}» по {coin} не принято: по этой монете уже ждёт «{}» (нажал: {}, с {}) окончания сделок: {}. Дождитесь \
         его или отмените («Отменить ожидание» на экране «Ручное управление»), потом нажмите «{what}» снова",
        x.what,
        x.who,
        x.since.format("%Y-%m-%d %H:%M:%S UTC"),
        x.waits_for.join("; ")
    )
}

/// Отказ входа новой сделки, пока ждёт кнопка. Принимает: ожидание. Ошибок нет.
pub fn paused(w: &ManualWait) -> String {
    format!(
        "новая сделка {} не начата: человек ({}) нажал «{}», и бот ждёт окончания сделок: {}; после них бот выполнит \
         «{}» и снова начнёт сделки {} (решение 405)",
        w.coin,
        w.who,
        w.what,
        w.waits_for.join("; "),
        w.what,
        w.coin
    )
}

/// Ответ «Отменить ожидание». Принимает: ожидание. Ошибок нет.
pub fn cancelled(w: &ManualWait) -> String {
    format!(
        "ожидание «{}» по {} (нажал: {}) отменено: действие не выполнено, новые сделки {} снова начинаются",
        w.what, w.coin, w.who, w.coin
    )
}

/// Сделки кончились — повтор кнопки. Принимает: монету, кнопку, кто нажал. Ошибок нет.
pub fn running(coin: &str, what: &str, who: &str) -> String {
    format!("сделки по {coin} закончились — выполняю «{what}» (нажал: {who})")
}
