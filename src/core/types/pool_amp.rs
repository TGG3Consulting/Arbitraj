//! Файл: core/types/pool_amp.rs
//! Что делает: состояние пула «V2 с усилением» (решение 287) — без названия площадки: реальные резервы пары, виртуальные
//! (усиленные) резервы, по которым идёт формула x·y=k, и комиссия обмена на блоке чтения (динамическая — меняется от
//! блока к блоку без событий пула). Вынесено из pool.rs (предел размера файла).
//! Кто вызывает: core/types/pool.rs (PoolState::AmpV2), адаптер DEX (pools/load_dmm.rs создаёт, math/dmm.rs считает).
//! От чего зависит: alloy-primitives, serde.
//! Настройки: нет.

use alloy_primitives::U256;
use serde::{Deserialize, Serialize};

/// Состояние пула «V2 с усилением» на блоке — боксируется в `PoolState::AmpV2`. Математика — в адаптере.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AmpV2Data {
    /// Реальный резерв token0 (выход обмена должен быть строго меньше реального резерва выхода).
    pub reserve0: U256,
    /// Реальный резерв token1.
    pub reserve1: U256,
    /// Виртуальный резерв token0 — по нему считается выход (у пула без усиления равен реальному).
    pub v_reserve0: U256,
    /// Виртуальный резерв token1.
    pub v_reserve1: U256,
    /// Комиссия обмена на блоке чтения — доля над 10^18 (точность пула).
    pub fee: U256,
}
