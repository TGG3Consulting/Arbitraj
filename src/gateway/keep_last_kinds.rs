//! Файл: gateway/keep_last_kinds.rs
//! Что делает: типы набора «ждут доставки» (gateway/keep_last.rs): ключ и его класс (Keyed), слот (Slot, Take),
//! проверка «ещё годно» при доставке (Check), итог предложения (Offer), счёт класса (Counts), настройка, прочитанная
//! не больше раза (Ask), итог быстрого пути (Fast). Отдельный файл — чтобы keep_last.rs держал только порядок
//! offer/deliver (ревью 324, Н6: не больше 200 строк); keep_last.rs реэкспортирует всё отсюда.
//! Кто вызывает: gateway/keep_last.rs, gateway/keep_last_state.rs (через реэкспорт keep_last).
//! От чего зависит: tokio::sync::mpsc (Permit).
//! Настроек нет.

use std::hash::Hash;

use tokio::sync::mpsc::Permit;

/// Ключ набора и его класс (счёт и правило 321 — по классу).
pub trait Keyed: Eq + Hash + Clone {
    /// Класс ключа (например: пулы площадки, стаканы площадки).
    type Class: Eq + Hash + Clone;
    /// Класс этого ключа. Ошибок нет.
    fn class(&self) -> Self::Class;
}

/// Что слот отдаёт доставщику.
pub enum Take<M, S> {
    /// Отправить сообщение; остаток слота (Some) ждёт в начале очереди.
    Send(M, Option<S>),
    /// Не отправлять (устарело).
    Skip,
}

/// Что хранится по ключу, пока он ждёт.
pub trait Slot: Sized {
    /// Сообщение канала.
    type Msg;
    /// Новое событие того же ключа, пока он ждёт. Возвращает: заменено ли ждавшее (счёт replaced). Ошибок нет.
    fn merge(&mut self, newer: Self) -> bool;
    /// Сообщение для отправки сразу (свежий слот — одно событие). Ошибок нет.
    fn now(self) -> Self::Msg;
    /// Доставщик: что отправить. Ошибок нет.
    fn take(self) -> Take<Self::Msg, Self>;
    /// Срочное: в начало очереди, не теряется. Ошибок нет.
    fn urgent(&self) -> bool;
    /// Начало ожидания ключа. Измеряется только при первом откладывании отслеживаемого слота.
    fn queue_start(&self) -> Option<std::time::Instant> {
        None
    }
    /// Место в канале уже получено, сообщение готово к передаче.
    fn measure_ready(&self, _start: std::time::Instant, _counts: &mut Counts) {}
}

/// Проверка «сообщение ещё годно» при доставке (например: пул DEX не снят и достоверен). Вызывается доставщиком.
pub trait Check<K, M> {
    /// Нужна ли проверка сообщению этого ключа (нет — отправляется без неё). Ошибок нет.
    fn needs(&self, key: &K) -> bool;
    /// Годно ли (false — не отправлять, счёт dropped). Ошибок нет.
    fn live(&self, key: &K, msg: &M) -> bool;
}

/// Без проверки.
impl<K, M> Check<K, M> for () {
    fn needs(&self, _: &K) -> bool {
        false
    }
    fn live(&self, _: &K, _: &M) -> bool {
        true
    }
}

/// Чем кончилось предложение события.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Offer {
    /// Ушло в канал сразу.
    Sent,
    /// Отложено; start — доставщика нет, его надо запустить.
    Deferred { start: bool },
    /// Ключ уже ждал — событие слито с ждущим (более свежее заменило прежнее); start — доставщика нет (упал), его
    /// надо запустить (ревью 324, Н3).
    Replaced { start: bool },
    /// Канал полон, откладывать не велено — потеряно (как до решений 321/324; считает вызывающий).
    Lost,
    /// Канал закрыт.
    Closed,
}

/// Счёт класса с прошлой записи журнала и сколько ждёт сейчас.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Counts {
    /// Отложено (новых ключей в наборе).
    pub deferred: u64,
    /// Заменено более свежим событием того же ключа, пока он ждал.
    pub replaced: u64,
    /// Доставлено доставщиком (сообщений).
    pub delivered: u64,
    /// Снято при доставке (Take::Skip или Check::live = false). Потерянные (Offer::Lost) считает вызывающий — без
    /// замка набора (ревью 324, Б2).
    pub dropped: u64,
    /// Ждут сейчас (ключей).
    pub waiting: usize,
    /// Максимальное ожидание ключа к моменту передачи отложенной книги в канал, за окно отчёта.
    pub max_book_wait_ms: Option<u64>,
    /// Максимальный возраст фактически передаваемой версии по её локальному received_at.
    pub max_book_age_ms: Option<u64>,
}

/// «Откладывать ли» (настройка): читается не больше раза и только когда без неё не решить.
pub struct Ask<F> {
    f: Option<F>,
    v: bool,
}

impl<F: FnOnce() -> bool> Ask<F> {
    /// Принимает: чтение настройки. Ошибок нет.
    pub fn new(f: F) -> Self {
        Self {
            f: Some(f),
            v: false,
        }
    }

    /// Значение (первый вызов читает, следующие — прочитанное). Ошибок нет.
    pub fn get(&mut self) -> bool {
        if let Some(f) = self.f.take() {
            self.v = f();
        }
        self.v
    }
}

/// Итог быстрого пути (ревью 324, Б1): набор пуст — без замка и без ключа.
pub enum Fast<'a, M> {
    /// Набор пуст и место в канале есть — отправить этим разрешением.
    Free(Permit<'a, M>),
    /// Набор пуст, канал полон.
    Full,
    /// В наборе кто-то ждёт (или доставляется) — только медленный путь под замком.
    Busy,
    /// Канал закрыт.
    Closed,
}
