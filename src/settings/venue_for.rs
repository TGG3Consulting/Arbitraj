//! Файл: settings/venue_for.rs
//! Что делает: решение 283 — признак настройки «площадки какого вида читают значение области «площадка»» (поле
//! SettingDef::venue_for). Только описание для интерфейса: экраны «Площадки» и «Настройки» не показывают строку у
//! площадки другого вида (ui/src/lib/settings.svelte.js shownAtVenue). Чтение, запись, проверка и хранение значений
//! его не учитывают.
//! Кто вызывает: settings/schema.rs (поле и .dex_venue()), settings/catalog/mod.rs (значение по умолчанию, тест).
//! От чего зависит: serde.
//! Настройки: нет.

use serde::Serialize;

/// Площадки какого вида читают значение области «площадка».
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub enum VenueFor {
    /// Любая площадка (биржа и DEX).
    Any,
    /// Только площадка вида DEX (адаптер DEX или ядро для площадки DEX); значение у биржи никто не читает.
    Dex,
}
