use super::code::{self, Version};
use super::live_proof::{self, Verdicts};
use super::live_record;

/// Короткая причина запрета для пары (версия сборки, сеть кошелька) — её же показывает интерфейс у недоступной кнопки
/// «Развернуть исполнитель». Ошибок нет.
pub fn not_accepted(v: Version, chain: Option<u64>) -> String {
    format!(
        "запись приёмки для версии {} не приняла на живых пулах ни одного класса шага (или её нет)",
        live_proof::pair(v, chain)
    )
}

/// Причина запрета развёртывания текущей сборки кошельком площадки сети `chain`. Возвращает: None — разрешено
/// (принят хотя бы один класс); Some — текст отказа с перечнем принятого и непринятого. Ошибок нет.
pub fn refusal_at(chain: Option<u64>) -> Option<String> {
    match live_proof::verdicts_current(chain) {
        Ok((v, list)) => refusal_for(v, chain, list),
        Err(e) => Some(format!(
            "Развёртывание исполнителя запрещено — сборка contracts/out/ не сверена: {e}"
        )),
    }
}

/// То же для данных вердиктов (проверяемо тестом). Возвращает: None — принят хотя бы один класс; иначе текст отказа.
/// Ошибок нет.
pub fn refusal_for(v: Version, chain: Option<u64>, list: &Verdicts) -> Option<String> {
    match list {
        Ok(l) if l.iter().any(|x| x.accepted) => None,
        _ => Some(format!(
            "Развёртывание исполнителя запрещено — {}. {}. Обходной настройки нет (решения 395, 399, 400, 461; \
             кошелёк с v2 работает как раньше).",
            not_accepted(v, chain),
            live_proof::listing_of(v, chain, list)
        )),
    }
}

/// Решение 461: закрыто ли развёртывание текущей сборки во ВСЕХ сетях записей (для подсказок без сети кошелька —
/// need_v3, exec_callback::need_v4): нет ни одной записи версии текущей сборки, принявшей класс. Ошибок нет.
pub fn closed_everywhere() -> bool {
    let Ok(v) = code::current_version() else {
        return true;
    };
    for j in live_record::all() {
        if j.version == v && opens(j) {
            return false;
        }
    }
    true
}

/// Приняла ли запись хотя бы один класс. Ошибок нет.
fn opens(j: &live_record::Judged) -> bool {
    match &j.verdicts {
        Ok(l) => l.iter().any(|x| x.accepted),
        Err(_) => false,
    }
}

/// Решение 399 (Н2): что делать маршруту или шагу, которому нужен исполнитель v3. Возвращает: пока развёртывание
/// закрыто во всех сетях записей — «нужен исполнитель v3; …» (без призыва переразвернуть); иначе — призыв
/// переразвернуть с оговоркой о сети. Ошибок нет.
pub fn need_v3() -> &'static str {
    need_v3_for(closed_everywhere())
}

/// То же при известном запрете (проверяемо тестом). Принимает: закрыто ли развёртывание. Ошибок нет.
pub fn need_v3_for(refused: bool) -> &'static str {
    if refused {
        "нужен исполнитель v3; запись приёмки текущей сборки не приняла ни одного класса шага — \
         развёртывание закрыто"
    } else {
        "переразверните исполнитель кошелька (экран «Маппинг кошельков»; кнопка открыта в сети, где \
         запись приёмки текущей сборки приняла класс шага)"
    }
}
